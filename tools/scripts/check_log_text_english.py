PY_LOG_METHODS = {'debug', 'info', 'warning', 'warn', 'error', 'exception', 'critical', 'fatal'}
PY_DIRECT_SINKS = {'print', 'sys.exit', 'SystemExit', 'exit', 'quit', 'sys.stderr.write', 'sys.stdout.write'}


def _py_dotted(node: ast.AST) -> str | None:
    parts = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        parts.append(node.id)
        return '.'.join(reversed(parts))
    return None


def _py_is_sink(call: ast.Call) -> bool:
    name = _py_dotted(call.func)
    if not name:
        return False
    if name == 'print':
        # print(..., file=fh) 写的是文件内容,不是控制台。
        for kw in call.keywords:
            if kw.arg == 'file' and _py_dotted(kw.value) not in ('sys.stdout', 'sys.stderr'):
                return False
        return True
    if name in PY_DIRECT_SINKS:
        return True
    head, _, last = name.rpartition('.')
    return last in PY_LOG_METHODS and 'log' in head.lower()


def scan_python(rel: str, src: str) -> list[Finding]:
    try:
        tree = ast.parse(src)
    except SyntaxError as exc:
        return [Finding(rel, exc.lineno or 0, 'python', 'syntax-error', str(exc))]
    lines = src.split('\n')
    parents: dict[ast.AST, ast.AST] = {}
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            parents[child] = node
    wrappers: set[str] = set()
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        params = {a.arg for a in fn.args.args + fn.args.kwonlyargs}
        if fn.args.vararg:
            params.add(fn.args.vararg.arg)
        for node in ast.walk(fn):
            if isinstance(node, ast.Call) and _py_is_sink(node):
                used = {n.id for a in list(node.args) + [k.value for k in node.keywords]
                        for n in ast.walk(a) if isinstance(n, ast.Name)}
                if used & params:
                    wrappers.add(fn.name)
                    break
    findings = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Constant) and isinstance(node.value, str)) or not CJK.search(node.value):
            continue
        p = parents.get(node)
        while p is not None and not isinstance(p, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Module)):
            if isinstance(p, ast.Raise):
                break
            if isinstance(p, ast.Call):
                name = _py_dotted(p.func) or ''
                if _py_is_sink(p) or name in wrappers:
                    findings.append(Finding(rel, node.lineno, 'python', name, lines[node.lineno - 1]))
                    break
            p = parents.get(p)
    return findings


