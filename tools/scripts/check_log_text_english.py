GO_LOG_METHODS = {
    'Info', 'Infof', 'Infov', 'Infow', 'Infoln', 'Error', 'Errorf', 'Errorv', 'Errorw', 'Errorln',
    'Debug', 'Debugf', 'Debugv', 'Debugw', 'Debugln', 'Slow', 'Slowf', 'Slowv', 'Sloww',
    'Severe', 'Severef', 'Stat', 'Statf', 'Alert', 'Must', 'Mustf', 'Warn', 'Warnf', 'Warnw', 'Warnln',
    'Warning', 'Warningf', 'Fatal', 'Fatalf', 'Fatalw', 'Fatalln', 'Panic', 'Panicf', 'Panicw', 'Panicln',
    'DPanic', 'DPanicf', 'DPanicw', 'Print', 'Printf', 'Println',
}
# 不是日志器、但碰巧有同名方法的接收者:错误构造、测试对象、字符串工具。
GO_NON_LOG_RECEIVERS = {'fmt', 'status', 'errors', 'xerrors', 'pkgerrors', 'grpcstatus', 't', 'b', 'tb', 'f',
                        'strings', 'bytes'}


def _go_tokens(src: str) -> list[tuple[str, int, int, int]]:
    toks = []
    i, n, line = 0, len(src), 1
    while i < n:
        c = src[i]
        if c == '\n':
            line += 1
            i += 1
            continue
        if c in ' \t\r﻿':
            i += 1
            continue
        if src.startswith('//', i):
            j = src.find('\n', i)
            i = n if j < 0 else j
            continue
        if src.startswith('/*', i):
            j = src.find('*/', i + 2)
            j = n if j < 0 else j + 2
            line += src.count('\n', i, j)
            i = j
            continue
        if c == '"':
            j = i + 1
            while j < n and src[j] not in '"\n':
                j += 2 if src[j] == '\\' else 1
            toks.append(('str', i, j + 1, line))
            i = j + 1
            continue
        if c == '`':
            j = src.find('`', i + 1)
            j = n if j < 0 else j + 1
            toks.append(('str', i, j, line))
            line += src.count('\n', i, j)
            i = j
            continue
        if c == "'":
            j = i + 1
            while j < n and src[j] not in "'\n":
                j += 2 if src[j] == '\\' else 1
            toks.append(('rune', i, j + 1, line))
            i = j + 1
            continue
        if c.isalpha() or c == '_':
            j = i
            while j < n and (src[j].isalnum() or src[j] == '_'):
                j += 1
            toks.append(('ident', i, j, line))
            i = j
            continue
        if c.isdigit():
            j = i
            while j < n and (src[j].isalnum() or src[j] in '._'):
                j += 1
            toks.append(('num', i, j, line))
            i = j
            continue
        toks.append(('punct', i, i + 1, line))
        i += 1
    return toks


def _go_callee(src: str, toks: list, k: int) -> str | None:
    """k 是 '(' 的下标;返回调用名,如 logx.Errorf、l.Logger.Infof、logger.Global.Warn。"""
    j = k - 1
    if j < 0 or toks[j][0] != 'ident':
        return None
    start, end = toks[j][1], toks[j][2]
    j -= 1
    while j >= 1 and src[toks[j][1]:toks[j][2]] == '.':
        prev = j - 1
        if toks[prev][0] == 'ident':
            start = toks[prev][1]
            j = prev - 1
            continue
        if src[toks[prev][1]:toks[prev][2]] == ')':
            depth, q = 0, prev
            while q >= 0:
                tq = src[toks[q][1]:toks[q][2]]
                if tq == ')':
                    depth += 1
                elif tq == '(':
                    depth -= 1
                    if depth == 0:
                        break
                q -= 1
            if q - 1 >= 0 and toks[q - 1][0] == 'ident':
                start = toks[q - 1][1]
                j = q - 2
                continue
        break
    return src[start:end]


def _go_first_arg(src: str, toks: list, k: int) -> str:
    depth, out = 0, []
    for t in toks[k + 1:]:
        tt = src[t[1]:t[2]]
        if tt in '([{':
            depth += 1
        elif tt in ')]}':
            if depth == 0:
                break
            depth -= 1
        elif tt == ',' and depth == 0:
            break
        out.append(tt)
    return ''.join(out)


def _go_sink(callee: str | None, first_arg: str) -> str | None:
    if not callee:
        return None
    if callee == 'panic':
        return 'panic'
    parts = callee.split('.')
    head, last = parts[0], parts[-1]
    if head in ('logx', 'log'):
        return callee
    if head == 'fmt':
        if last in ('Print', 'Printf', 'Println'):
            return callee
        if last in ('Fprint', 'Fprintf', 'Fprintln') and first_arg in ('os.Stdout', 'os.Stderr'):
            return callee
        return None
    if last in GO_LOG_METHODS and len(parts) >= 2 and head not in GO_NON_LOG_RECEIVERS:
        return callee
    return None


def scan_go(rel: str, src: str) -> list[Finding]:
    toks = _go_tokens(src)
    lines = src.split('\n')
    stack: list[str | None] = []
    findings = []
    for k, t in enumerate(toks):
        if t[0] == 'punct':
            ch = src[t[1]]
            if ch == '(':
                callee = _go_callee(src, toks, k)
                first = _go_first_arg(src, toks, k) if callee and callee.startswith('fmt.Fprint') else ''
                stack.append(_go_sink(callee, first))
            elif ch in '{[':
                stack.append(None)
            elif ch in ')}]' and stack:
                stack.pop()
            continue
        if t[0] != 'str' or not CJK.search(src[t[1]:t[2]]):
            continue
        sinks = [s for s in stack if s]
        if sinks:
            findings.append(Finding(rel, t[3], 'go', sinks[-1], lines[t[3] - 1]))
    return findings


