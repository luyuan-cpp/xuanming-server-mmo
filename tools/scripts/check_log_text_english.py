def scan_file(rel: str, src: str) -> list[Finding]:
    """单文件入口(单元测试直接调用):按路径决定语言与是否跳过。"""
    if is_excluded_path(rel) or is_test_path(rel):
        return []
    language = language_of(rel)
    if language is None or not CJK.search(src) or is_generated_source(rel, src):
        return []
    # Python 的 AST 是广度优先遍历,按行号排一次,输出与测试都不依赖遍历顺序。
    return sorted(SCANNERS[language](rel, src), key=lambda f: f.line)


def scan_repository(root: Path) -> list[Finding]:
    findings = []
    for rel in list_candidate_files(root):
        if is_excluded_path(rel) or is_test_path(rel) or language_of(rel) is None:
            continue
        try:
            src = (root / rel).read_text(encoding='utf-8-sig', errors='replace')
        except OSError:
            continue
        findings.extend(scan_file(rel, src))
    findings.sort(key=lambda f: (f.path, f.line))
    return findings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description='Fail when log / console output literals contain CJK text (AGENTS.md §2).')
    parser.add_argument('--root', default=str(Path(__file__).resolve().parents[2]), help='repository root')
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    if not (root / 'AGENTS.md').is_file():
        print(f'error: {root} does not look like the repository root (AGENTS.md not found)', file=sys.stderr)
        return 2
    try:
        entries = load_allowlist(root / ALLOWLIST_REL)
    except ValueError as exc:
        print(f'error: {exc}', file=sys.stderr)
        return 2
    findings, stale = apply_allowlist(scan_repository(root), entries)
    for f in findings:
        print(f.render())
    for e in stale:
        print(f'{ALLOWLIST_REL}:{e.source_line}: stale allowlist entry (no finding matches): {e.path} {e.fragment!r}')
    if findings or stale:
        print(f'log text check FAILED: {len(findings)} CJK literal(s) in log/console calls, {len(stale)} stale allowlist entr(ies). '
              f'Write log text in English (AGENTS.md §2); see the header of tools/scripts/check_log_text_english.py '
              f'for what is covered and how to register a justified exception.', file=sys.stderr)
        return 1
    print('log text check passed: no CJK literals in log/console calls')
    return 0


if __name__ == '__main__':
    sys.exit(main())
