PS_OUTPUT_CMDLETS = {'write-host', 'write-warning', 'write-output', 'write-verbose', 'write-information'}
PS_STATEMENT_STARTS = {None, 'nl', ';', '{', '(', '|', '&&', '||'}


def _ps_scan_dq(src: str, i: int) -> int:
    """i 指向开头的双引号;返回结束引号之后的下标。处理反引号转义、"" 与 $( ) 里嵌套的字符串。"""
    n = len(src)
    j = i + 1
    while j < n:
        c = src[j]
        if c == '`':
            j += 2
            continue
        if c == '"':
            if j + 1 < n and src[j + 1] == '"':
                j += 2
                continue
            return j + 1
        if c == '$' and j + 1 < n and src[j + 1] == '(':
            j = _ps_scan_subexpression(src, j + 2)
            continue
        j += 1
    return n


def _ps_scan_sq(src: str, i: int) -> int:
    n = len(src)
    j = i + 1
    while j < n:
        if src[j] == "'":
            if j + 1 < n and src[j + 1] == "'":
                j += 2
                continue
            return j + 1
        j += 1
    return n


def _ps_scan_subexpression(src: str, j: int) -> int:
    """j 指向 $( 之后;返回与之配对的 ) 之后的下标。"""
    n, depth = len(src), 1
    while j < n and depth:
        c = src[j]
        if c == '"':
            j = _ps_scan_dq(src, j)
            continue
        if c == "'":
            j = _ps_scan_sq(src, j)
            continue
        if c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
        j += 1
    return j


def _ps_tokens(src: str) -> list[tuple[str, str, int]]:
    toks: list[tuple[str, str, int]] = []
    i, n, line = 0, len(src), 1
    while i < n:
        c = src[i]
        if c == '\n':
            toks.append(('nl', '\n', line))
            line += 1
            i += 1
            continue
        if c in ' \t\r﻿':
            i += 1
            continue
        if c == '`' and i + 1 < n and src[i + 1] in '\r\n':
            # 反引号续行:吃掉换行,语句继续。
            i += 1
            while i < n and src[i] in '\r':
                i += 1
            if i < n and src[i] == '\n':
                line += 1
                i += 1
            continue
        if src.startswith('<#', i):
            j = src.find('#>', i + 2)
            j = n if j < 0 else j + 2
            line += src.count('\n', i, j)
            i = j
            continue
        if c == '#':
            j = src.find('\n', i)
            i = n if j < 0 else j
            continue
        if c == '@' and i + 1 < n and src[i + 1] in '"\'':
            quote = src[i + 1]
            eol = src.find('\n', i)
            if eol >= 0 and src[i + 2:eol].strip() == '':
                end = src.find('\n' + quote + '@', eol)
                if end < 0:
                    end = n - 1
                end = min(n, end + 3)
                toks.append(('str', src[i:end], line))
                line += src.count('\n', i, end)
                i = end
                continue
        if c == '"':
            j = _ps_scan_dq(src, i)
            toks.append(('str', src[i:j], line))
            line += src.count('\n', i, j)
            i = j
            continue
        if c == "'":
            j = _ps_scan_sq(src, i)
            toks.append(('str', src[i:j], line))
            line += src.count('\n', i, j)
            i = j
            continue
        if src.startswith('&&', i) or src.startswith('||', i):
            toks.append(('punct', src[i:i + 2], line))
            i += 2
            continue
        if c in '(){}[];|,=+':
            toks.append(('punct', c, line))
            i += 1
            continue
        j = i
        while j < n and src[j] not in ' \t\r\n(){}[];|,=+"\'`#':
            j += 1
        if j == i:
            j = i + 1
        toks.append(('word', src[i:j], line))
        i = j
    return toks


def scan_powershell(rel: str, src: str) -> list[Finding]:
    toks = _ps_tokens(src)
    lines = src.split('\n')
    findings = []
    prev_sig: str | None = None
    for k, (kind, text, line) in enumerate(toks):
        if kind == 'word' and text.lower() in PS_OUTPUT_CMDLETS and prev_sig in PS_STATEMENT_STARTS:
            depth = 0
            for kind2, text2, line2 in toks[k + 1:]:
                if kind2 == 'punct' and text2 in '([{':
                    depth += 1
                elif kind2 == 'punct' and text2 in ')]}':
                    if depth == 0:
                        break
                    depth -= 1
                elif depth == 0 and (kind2 == 'nl' or (kind2 == 'punct' and text2 in (';', '|', '&&', '||'))):
                    break
                elif kind2 == 'str' and CJK.search(text2):
                    findings.append(Finding(rel, line2, 'powershell', text, lines[line2 - 1]))
        if kind == 'nl':
            prev_sig = 'nl'
        elif kind == 'punct':
            prev_sig = text
        else:
            prev_sig = 'value'
    return findings


