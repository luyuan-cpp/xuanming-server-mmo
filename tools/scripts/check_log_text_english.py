def list_candidate_files(root: Path) -> list[str]:
    """优先用 git 列出受跟踪与未忽略的新文件;没有 git 时退回目录遍历。"""
    try:
        out = subprocess.run(['git', '-C', str(root), 'ls-files', '-co', '--exclude-standard', '--', *SCAN_ROOTS],
                             capture_output=True, check=True, env=dict(os.environ, GIT_NO_LAZY_FETCH='1'))
        files = [p for p in out.stdout.decode('utf-8', 'replace').split('\n') if p]
        return sorted(set(files))
    except (OSError, subprocess.CalledProcessError):
        files = []
        for top in SCAN_ROOTS:
            for dirpath, dirnames, filenames in os.walk(root / top):
                dirnames[:] = [d for d in dirnames if d not in SKIP_DIR_NAMES]
                for name in filenames:
                    files.append(Path(dirpath, name).relative_to(root).as_posix())
        return sorted(files)


def is_excluded_path(rel: str) -> bool:
    parts = rel.split('/')
    if parts[0] not in SCAN_ROOTS:
        return True
    if rel.startswith('tools/archived/'):
        return True
    return any(p in SKIP_DIR_NAMES for p in parts[:-1])


def is_test_path(rel: str) -> bool:
    name = rel.rsplit('/', 1)[-1]
    parts = rel.split('/')[:-1]
    if any(p in ('tests', 'test', 'testdata') for p in parts) or '/src/test/' in rel:
        return True
    return (name.endswith('_test.go') or name.endswith('.tests.ps1') or name.endswith('Test.java')
            or name.endswith('Tests.java') or (name.startswith('test_') and name.endswith('.py'))
            or name.endswith('_test.py') or name == 'conftest.py')


def is_generated_source(rel: str, src: str) -> bool:
    name = rel.rsplit('/', 1)[-1]
    if '.pb.' in name or name.endswith('_pb2.py'):
        return True
    head = src[:2000]
    return (('Code generated' in head and 'DO NOT EDIT' in head) or 'DO NOT EDIT' in head
            or 'Generated by the protocol buffer compiler' in head)


def language_of(rel: str) -> str | None:
    name = rel.rsplit('/', 1)[-1]
    low = name.lower()
    top = rel.split('/', 1)[0]
    if low.endswith('.go'):
        return 'go' if top in ('go', 'robot', 'tools') else None
    if low.endswith(('.cpp', '.cc', '.h', '.hpp', '.inl', '.ipp')):
        return 'cpp' if top == 'cpp' else None
    if low.endswith('.java'):
        return 'java' if top == 'java' and '/src/main/' in rel else None
    if low.endswith('.py'):
        return 'python' if top in ('tools', 'deploy') else None
    if low.endswith(('.ps1', '.psm1')):
        return 'powershell' if top in ('tools', 'deploy') else None
    if low.endswith(('.sh', '.bash')) or low == 'dockerfile' or low.startswith('dockerfile.'):
        return 'shell' if top in ('tools', 'deploy', 'robot') else None
    return None


