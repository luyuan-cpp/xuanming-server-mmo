SH_OUTPUT = re.compile(r'(^|[\s;&|({`])(echo|printf)(\s|$)')
SH_HEREDOC = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")


def _sh_strip_comment(raw: str) -> str:
    quote = None
    for j, ch in enumerate(raw):
        if quote:
            if ch == '\\' and quote == '"':
                continue
            if ch == quote:
                quote = None
            continue
        if ch in '"\'':
            quote = ch
        elif ch == '#' and (j == 0 or raw[j - 1] in ' \t;'):
            return raw[:j]
    return raw


def scan_shell(rel: str, src: str) -> list[Finding]:
    findings = []
    heredoc: str | None = None
    for no, raw in enumerate(src.split('\n'), start=1):
        if heredoc is not None:
            if raw.strip() == heredoc:
                heredoc = None
            continue
        code = _sh_strip_comment(raw)
        m = SH_HEREDOC.search(code)
        if m:
            heredoc = m.group(2)
        if CJK.search(code) and SH_OUTPUT.search(code):
            findings.append(Finding(rel, no, 'shell', 'echo/printf', raw))
    return findings


SCANNERS = {
    'go': scan_go,
    'cpp': scan_cpp,
    'java': scan_java,
    'python': scan_python,
    'powershell': scan_powershell,
    'shell': scan_shell,
}


