CJK = re.compile(r'[　-〿㐀-䶿一-鿿豈-﫿＀-￯]')

SCAN_ROOTS = ('go', 'cpp', 'java', 'robot', 'tools', 'deploy')
SKIP_DIR_NAMES = {'vendor', 'third_party', 'thirdparty', 'external', 'node_modules', 'generated',
                  '__pycache__', 'target', '.git'}
ALLOWLIST_REL = 'tools/scripts/log_text_english_allowlist.txt'


@dataclass(frozen=True)
class Finding:
    path: str
    line: int
    language: str
    sink: str
    line_text: str

    def render(self) -> str:
        text = self.line_text.strip()
        if len(text) > 160:
            text = text[:160] + '...'
        return f'{self.path}:{self.line}: [{self.language} {self.sink}] {text}'


@dataclass(frozen=True)
class AllowEntry:
    path: str
    fragment: str
    reason: str
    source_line: int


