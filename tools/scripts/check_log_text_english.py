CPP_CONSOLE = {'cout', 'cerr', 'clog', 'printf', 'fprintf', 'puts', 'fputs', 'wprintf', 'perror'}


def _cpp_tokens(src: str) -> list[tuple[str, int, int, int]]:
    toks = []
    i, n, line = 0, len(src), 1
    while i < n:
        c = src[i]
        if c == '\n':
            line += 1
            i += 1
            continue
        if c in ' \t\r\f\v﻿':
            i += 1
            continue
        if c == '\\' and i + 1 < n and src[i + 1] in '\r\n':
            i += 1
            continue
        if src.startswith('//', i):
            j = src.find('\n', i)
            i = n if j < 0 else j
            continue
        if src.startswith('/*', i):
            j = src.find('*/', i + 2)
            j = n if j < 0 else j + 2
            line += src.count('\n', i, j)
            i = j
            continue
        raw = re.match(r'(u8|u|U|L)?R"([^()\\ ]{0,16})\(', src[i:i + 24])
        if raw and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == '_')):
            marker = ')' + raw.group(2) + '"'
            j = src.find(marker, i + raw.end())
            j = n if j < 0 else j + len(marker)
            toks.append(('str', i, j, line))
            line += src.count('\n', i, j)
            i = j
            continue
        lit = re.match(r'(u8|u|U|L)?"', src[i:i + 3])
        if lit and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == '_') or lit.group(1) is None):
            j = i + lit.end()
            while j < n and src[j] not in '"\n':
                j += 2 if src[j] == '\\' else 1
            toks.append(('str', i, j + 1, line))
            i = j + 1
            continue
        if c == "'":
            j = i + 1
            while j < n and src[j] not in "'\n":
                j += 2 if src[j] == '\\' else 1
            toks.append(('char', i, j + 1, line))
            i = j + 1
            continue
        if c.isalpha() or c == '_':
            j = i
            while j < n and (src[j].isalnum() or src[j] == '_'):
                j += 1
            toks.append(('ident', i, j, line))
            i = j
            continue
        if c.isdigit():
            j = i
            while j < n and (src[j].isalnum() or src[j] in "._'"):
                j += 1
            toks.append(('num', i, j, line))
            i = j
            continue
        if c == '#':
            toks.append(('pp', i, i + 1, line))
            i += 1
            continue
        toks.append(('punct', i, i + 1, line))
        i += 1
    return toks


def _cpp_statement_sink(src: str, toks: list, k: int) -> str | None:
    """从字面量往回走到语句开头,语句里出现 LOG_* 或控制台输出就算日志。"""
    j = k - 1
    while j >= 0:
        kind, a, b, _ = toks[j]
        text = src[a:b]
        if kind == 'pp' or (kind == 'punct' and text in ';{}'):
            break
        if kind == 'ident':
            if text.startswith('LOG_'):
                return text
            if text in CPP_CONSOLE:
                return text
        j -= 1
    return None


def scan_cpp(rel: str, src: str) -> list[Finding]:
    toks = _cpp_tokens(src)
    lines = src.split('\n')
    findings = []
    for k, t in enumerate(toks):
        if t[0] != 'str' or not CJK.search(src[t[1]:t[2]]):
            continue
        sink = _cpp_statement_sink(src, toks, k)
        if sink:
            findings.append(Finding(rel, t[3], 'cpp', sink, lines[t[3] - 1]))
    return findings


