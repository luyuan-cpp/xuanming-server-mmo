def load_allowlist(path: Path) -> list[AllowEntry]:
    entries = []
    if not path.is_file():
        return entries
    for no, raw in enumerate(path.read_text(encoding='utf-8').split('\n'), start=1):
        line = raw.rstrip('\r')
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        cols = line.split('\t')
        if len(cols) != 3 or not all(c.strip() for c in cols):
            raise ValueError(f'{ALLOWLIST_REL}:{no}: expected "path<TAB>fragment<TAB>reason", got {line!r}')
        entries.append(AllowEntry(cols[0].strip(), cols[1], cols[2].strip(), no))
    return entries


def apply_allowlist(findings: list[Finding], entries: list[AllowEntry]) -> tuple[list[Finding], list[AllowEntry]]:
    used: set[AllowEntry] = set()
    remaining = []
    for f in findings:
        hit = next((e for e in entries if e.path == f.path and e.fragment in f.line_text), None)
        if hit is None:
            remaining.append(f)
        else:
            used.add(hit)
    stale = [e for e in entries if e not in used]
    return remaining, stale


