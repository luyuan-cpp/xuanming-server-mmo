JAVA_LOG_RECEIVERS = {'log', 'LOG', 'logger', 'LOGGER', 'Log', 'LOGGER_AUDIT', 'auditLog', 'AUDIT_LOG'}
JAVA_LOG_METHODS = {'trace', 'debug', 'info', 'warn', 'error'}


def _java_tokens(src: str) -> list[tuple[str, str, int]]:
    toks = []
    i, n, line = 0, len(src), 1
    while i < n:
        c = src[i]
        if c == '\n':
            line += 1
            i += 1
            continue
        if c in ' \t\r﻿':
            i += 1
            continue
        if src.startswith('//', i):
            j = src.find('\n', i)
            i = n if j < 0 else j
            continue
        if src.startswith('/*', i):
            j = src.find('*/', i + 2)
            j = n if j < 0 else j + 2
            line += src.count('\n', i, j)
            i = j
            continue
        if src.startswith('"""', i):
            j = src.find('"""', i + 3)
            j = n if j < 0 else j + 3
            toks.append(('str', src[i:j], line))
            line += src.count('\n', i, j)
            i = j
            continue
        if c == '"':
            j = i + 1
            while j < n and src[j] not in '"\n':
                j += 2 if src[j] == '\\' else 1
            toks.append(('str', src[i:j + 1], line))
            i = j + 1
            continue
        if c == "'":
            j = i + 1
            while j < n and src[j] not in "'\n":
                j += 2 if src[j] == '\\' else 1
            toks.append(('chr', src[i:j + 1], line))
            i = j + 1
            continue
        if c.isalpha() or c in '_$':
            j = i
            while j < n and (src[j].isalnum() or src[j] in '_$'):
                j += 1
            toks.append(('id', src[i:j], line))
            i = j
            continue
        toks.append(('p', c, line))
        i += 1
    return toks


def _java_sink(toks: list, k: int) -> str | None:
    j = k - 1
    if j < 0 or toks[j][0] != 'id':
        return None
    parts = [toks[j][1]]
    j -= 1
    while j >= 1 and toks[j][1] == '.' and toks[j - 1][0] == 'id':
        parts.append(toks[j - 1][1])
        j -= 2
    parts.reverse()
    name = '.'.join(parts)
    if len(parts) >= 2 and parts[-1] in JAVA_LOG_METHODS and parts[-2] in JAVA_LOG_RECEIVERS:
        return name
    if name.startswith(('System.out.', 'System.err.')):
        return name
    return None


def scan_java(rel: str, src: str) -> list[Finding]:
    toks = _java_tokens(src)
    lines = src.split('\n')
    stack: list[str | None] = []
    findings = []
    for k, (kind, text, line) in enumerate(toks):
        if kind == 'p':
            if text == '(':
                stack.append(_java_sink(toks, k))
            elif text == ')' and stack:
                stack.pop()
            continue
        if kind != 'str' or not CJK.search(text):
            continue
        sinks = [s for s in stack if s]
        if sinks:
            findings.append(Finding(rel, line, 'java', sinks[-1], lines[line - 1]))
    return findings


