class PowerShellTest(unittest.TestCase):
    REL = "tools/scripts/demo.ps1"

    def test_output_cmdlets_are_reported_including_continued_statements(self):
        src = (
            f"Write-Host '{ZH}'\n"
            f'if ($x) {{ Write-Warning "{ZH}: $x" }}\n'
            "Write-Warning ($summary + ': prefix ' +\n"
            f"    '{ZH}')\n"
            "Write-Host `\n"
            f'    "{ZH}"\n'
            f'Write-Host "a $(if ($y) {{ "{ZH}" }}) b"\n'
        )
        self.assertEqual([1, 2, 4, 6, 7], [line for line, _ in sinks(self.REL, src)])

    def test_throw_assignments_comments_and_next_statements_are_not_reported(self):
        src = (
            f"# {ZH}\n"
            f"<# {ZH}\n{ZH} #>\n"
            f'throw "{ZH}"\n'
            f"$reason = '{ZH}'\n"
            "Write-Host 'ok'\n"
            f"$next = '{ZH}'\n"
            f"Write-Error '{ZH}'\n"
            "Write-Host @'\n"
            "plain english here-string\n"
            "'@\n"
        )
        self.assertEqual([], sinks(self.REL, src))

    def test_here_string_passed_to_write_host_is_reported(self):
        src = "Write-Host @\"\n" f"{ZH}\n" "\"@\n"
        self.assertEqual([1], [line for line, _ in sinks(self.REL, src)])


class ShellTest(unittest.TestCase):
    REL = "tools/scripts/demo.sh"

    def test_echo_and_printf_lines_are_reported(self):
        src = (
            "#!/usr/bin/env bash\n"
            f"echo '{ZH}' >&2\n"
            f'[ -f "$x" ] || {{ echo "{ZH}: $x" >&2; exit 1; }}\n'
            f"printf '%s\\n' '{ZH}'\n"
        )
        self.assertEqual([2, 3, 4], [line for line, _ in sinks(self.REL, src)])

    def test_comments_heredocs_and_dockerfile_rules(self):
        src = (
            f"# {ZH}\n"
            "cat > \"$cfg\" <<EOF\n"
            f"echo {ZH}\n"
            "EOF\n"
            f"value='{ZH}'  # {ZH}\n"
        )
        self.assertEqual([], sinks(self.REL, src))
        docker = f'RUN test -x /bin/app || (echo "{ZH}" && exit 1)\n'
        self.assertEqual([1], [line for line, _ in sinks("deploy/k8s/Dockerfile.go-svc", docker)])


class AllowlistTest(unittest.TestCase):
    def test_matching_entry_suppresses_and_unused_entry_is_stale(self):
        findings = CHECKER.scan_file("tools/scripts/demo.py", f'print("{ZH}")\nprint("other {ZH}")\n')
        entries = [
            CHECKER.AllowEntry("tools/scripts/demo.py", "other", "demo reason", 1),
            CHECKER.AllowEntry("tools/scripts/gone.py", "x", "fixed already", 2),
        ]
        remaining, stale = CHECKER.apply_allowlist(findings, entries)
        self.assertEqual([1], [f.line for f in remaining])
        self.assertEqual(["tools/scripts/gone.py"], [e.path for e in stale])

    def test_malformed_line_is_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "allow.txt"
            path.write_text("# header\ntools/scripts/demo.py\tonly-two-columns\n", encoding="utf-8")
            with self.assertRaises(ValueError):
                CHECKER.load_allowlist(path)

    def test_repository_allowlist_parses(self):
        CHECKER.load_allowlist(REPO / CHECKER.ALLOWLIST_REL)


