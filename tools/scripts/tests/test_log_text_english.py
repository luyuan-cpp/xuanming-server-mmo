"""check_log_text_english.py(AGENTS.md §2 日志文案英文守卫)的单元测试;只喂内存里的源码片段,不扫仓库。

全仓扫描由 CI 直接运行 tools/scripts/check_log_text_english.py 完成;这里钉住每种语言「该报的报、
不该报的不报」,以及例外登记的匹配与失效判定。
"""

import importlib.util
from pathlib import Path
import tempfile
import unittest


REPO = Path(__file__).resolve().parents[3]
SPEC = importlib.util.spec_from_file_location("check_log_text_english", REPO / "tools/scripts/check_log_text_english.py")
CHECKER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CHECKER)

ZH = "中文"


def sinks(rel, src):
    return [(f.line, f.sink) for f in CHECKER.scan_file(rel, src)]


class GoTest(unittest.TestCase):
    REL = "go/demo/internal/logic/demo.go"

    def test_direct_log_calls_are_reported(self):
        src = (
            "package logic\n"
            f'func a() {{ logx.Errorf("{ZH} %v", err) }}\n'
            f'func b() {{ l.Logger.Infof("{ZH}") }}\n'
            f'func c() {{ logger.Global.Warn("{ZH}", zap.Error(err)) }}\n'
            f'func d() {{ zap.L().Debug("{ZH}") }}\n'
            f'func e() {{ panic("{ZH}") }}\n'
            f'func f() {{ fmt.Fprintf(os.Stderr, "{ZH}\\n") }}\n'
            f'func g() {{ fmt.Println("{ZH}") }}\n'
        )
        self.assertEqual([2, 3, 4, 5, 6, 7, 8], [line for line, _ in sinks(self.REL, src)])

    def test_literal_nested_inside_a_log_call_is_reported(self):
        src = f'package x\nfunc a() {{ logx.Must(fmt.Errorf("{ZH}: %w", err)) }}\n'
        self.assertEqual([(2, "logx.Must")], sinks(self.REL, src))

    def test_errors_comments_and_writers_are_not_reported(self):
        src = (
            "package logic\n"
            f"// {ZH}\n"
            f'func a() error {{ return fmt.Errorf("{ZH} %w", err) }}\n'
            f'func b() error {{ return errors.New("{ZH}") }}\n'
            f'func c() error {{ return status.Error(codes.Internal, "{ZH}") }}\n'
            f'func d() {{ fmt.Fprintf(w, "{ZH}") }}\n'
            f'var tip = "{ZH}"\n'
        )
        self.assertEqual([], sinks(self.REL, src))

    def test_test_and_generated_files_are_skipped(self):
        src = f'package x\nfunc a() {{ logx.Info("{ZH}") }}\n'
        self.assertEqual([], sinks("go/demo/demo_test.go", src))
        self.assertEqual([], sinks(self.REL, "// Code generated by protoc. DO NOT EDIT.\n" + src))
        self.assertEqual([], sinks("go/demo/vendor/x/x.go", src))


class CppTest(unittest.TestCase):
    REL = "cpp/libs/services/scene/player/system/demo.cpp"

