package internal

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
	"sync"

	messageoption "github.com/luyuancpp/protooption"
	"go.uber.org/zap"

	_config "protogen/internal/config"
	"protogen/internal/utils"
	"protogen/logger"
)

// WriteGoRouteTable 生成客户端 RPC 路由服的路由表(docs/design/client-rpc-router.md D31):
//
//	message_id → {gRPC 全限定方法, 目标节点类型, 是否客户端协议, 服务名, 方法名}
//
// 与路由服自己的 message_id.go 同包(generated/pb/game),键直接用生成常量,
// 消息号写错编译期就炸,不存在手抄表漂移。只收 gRPC 形态的方法(cc_generic_services
// 的 Scene 消息走 gate→scene 的 muduo TCP,永远到不了路由服);DB 域整个跳过。
//
// 路由服按表转发原始字节:FullMethod 是 protoc 生成的 "/<package>.<Service>/<Method>"
// (proto 无 package 时为 "/<Service>/<Method>"),NodeType 是发现前缀与 zone 过滤的依据。
func WriteGoRouteTable(wg *sync.WaitGroup) {
	wg.Add(1)
	go func() {
		defer wg.Done()

		outputPath := _config.Global.Paths.ClientRpcRouterRouteTableFile
		if strings.TrimSpace(outputPath) == "" {
			logger.Global.Warn("client_rpc_router_route_table_file not configured, skipping route table generation")
			return
		}

		type routeEntry struct {
			constName      string
			fullMethod     string
			nodeEnum       string
			clientProtocol bool
			service        string
			method         string
		}

		var entries []routeEntry
		for _, service := range GlobalRPCServiceList {
			if len(service.Methods) == 0 {
				continue
			}
			if IsFileBelongToNode(service.Fd, messageoption.NodeType_NODE_DB) {
				continue
			}
			// Scene 等 cc_generic_services 服务是 muduo TCP RPC,不经路由服
			if service.CcGenericServices() {
				continue
			}

			serviceFullName := service.Service()
			if pkg := service.Package(); pkg != "" {
				serviceFullName = pkg + "." + service.Service()
			}
			nodeEnum := "base.ENodeType_" + service.NodeServiceForCpp() + "NodeService"
			clientProtocol := IsClientProtocolService(service.ServiceDescriptorProto)

			for _, method := range service.Methods {
				entries = append(entries, routeEntry{
					constName:      method.KeyName() + _config.Global.Naming.MessageId,
					fullMethod:     "/" + serviceFullName + "/" + method.Method(),
					nodeEnum:       nodeEnum,
					clientProtocol: clientProtocol,
					service:        service.Service(),
					method:         method.Method(),
				})
			}
		}

		// 稳定输出:按常量名排序,重生成不产生无意义 diff
		sort.Slice(entries, func(i, j int) bool { return entries[i].constName < entries[j].constName })

		var sb strings.Builder
		sb.WriteString("// Code generated by protogen. DO NOT EDIT.\n")
		sb.WriteString("//\n")
		sb.WriteString("// 客户端 RPC 路由表(docs/design/client-rpc-router.md D31):message_id → 目标 gRPC 方法 / 节点类型。\n")
		sb.WriteString("// 键是本包 message_id.go 里的生成常量;事实源是 proto/ 下各服务的 OptionFileDefaultNode /\n")
		sb.WriteString("// OptionIsClientProtocolService 选项。改 proto 后重跑 proto-gen-run,不要手改。\n\n")
		sb.WriteString("package game\n\n")
		sb.WriteString("import base \"proto/common/base\"\n\n")
		sb.WriteString("// RouteEntry 是一条客户端消息号的转发目标。\n")
		sb.WriteString("type RouteEntry struct {\n")
		sb.WriteString("\tFullMethod     string         // gRPC 全限定方法名,如 \"/match.MatchService/JoinQueue\"\n")
		sb.WriteString("\tNodeType       base.ENodeType // 目标节点类型:决定 etcd 发现前缀与 zone 过滤\n")
		sb.WriteString("\tClientProtocol bool           // 所属 service 是否标了 OptionIsClientProtocolService\n")
		sb.WriteString("\tService        string\n")
		sb.WriteString("\tMethod         string\n")
		sb.WriteString("}\n\n")
		sb.WriteString("// RouteTable 覆盖全部 gRPC 形态的服务方法(Scene 等 muduo TCP RPC 不在此表)。\n")
		sb.WriteString("var RouteTable = map[uint32]RouteEntry{\n")
		for _, e := range entries {
			sb.WriteString(fmt.Sprintf("\t%s: {FullMethod: %q, NodeType: %s, ClientProtocol: %t, Service: %q, Method: %q},\n",
				e.constName, e.fullMethod, e.nodeEnum, e.clientProtocol, e.service, e.method))
		}
		sb.WriteString("}\n\n")
		sb.WriteString("// LookupRoute 按消息号查转发目标;不存在返回 false。\n")
		sb.WriteString("func LookupRoute(messageId uint32) (RouteEntry, bool) {\n")
		sb.WriteString("\tentry, ok := RouteTable[messageId]\n")
		sb.WriteString("\treturn entry, ok\n")
		sb.WriteString("}\n")

		// 过一遍 gofmt:map 字面量的列对齐靠手拼做不到,生成物不该被 gofmt -l 点名
		formatted, err := format.Source([]byte(sb.String()))
		if err != nil {
			logger.Global.Fatal("Generated route table is not valid Go",
				zap.String("file_path", outputPath),
				zap.Error(err))
		}
		if err := utils.WriteFileIfChanged(outputPath, formatted); err != nil {
			logger.Global.Fatal("Failed to write client rpc router route table",
				zap.String("file_path", outputPath),
				zap.Error(err))
		}
		logger.Global.Info("Client rpc router route table generated",
			zap.String("file_path", outputPath),
			zap.Int("entries", len(entries)))
	}()
}
