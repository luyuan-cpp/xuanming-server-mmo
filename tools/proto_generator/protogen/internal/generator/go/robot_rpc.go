// robot 类型化调用桩(docs/design/client-rpc-callback.md §5.5):每个至少有一个 REQUEST / ONE_WAY 方法的客户端协议服务
// 一个文件 robot/generated/rpc/<snake_service>.go(Go 包 rpc),与 Unity 的 <Service>Rpc 静态类对应。
//
// 命名契约(robot 场景按它调用,改动即破坏调用方):
//   - 每服务一个导出的零值变量 + 未导出的空结构类型:var <Service> <lowerCamelService>Rpc,
//     调用形如 rpc.ClientPlayerFriend.AddFriend(...);
//   - REQUEST:<Method>(c, req, timeout, done) 走 pkg.GameClient.Call;<Method>Sync(ctx, c, req, timeout) 走 CallSync;
//   - ONE_WAY:<Method>(c, req) error 走 pkg.GameClient.SendRequest(id = 0);
//   - PUSH 与 SERVER_ONLY 不生成调用函数(推送仍由 robot/logic/handler 的注册表按 message_id 派发)。
//
// 方法形态来自 internal.ClassifyClientRpcServices(proto option OptionClientRpcKind),本文件不自行推断。

const (
	// robotRpcTemplatePath 相对 protogen 根目录(生成器的工作目录)。
	robotRpcTemplatePath = "internal/template/robot_rpc.go.tmpl"

	// robotRpcSourceMarker 是模板产物开头两行的固定部分:Go 标准生成标记 + 来源行前缀。目录整写只删除以它开头的 .go,
	// robot_rpc_dir 误配到别的目录时,手写代码与其它工具的产物(例如只有第一行相同的 route_table.go)不会被当成旧桩删掉。
	// 改模板头部时同步改这里。
	robotRpcSourceMarker = "// Code generated by protogen. DO NOT EDIT.\n// Source: "

	// robotMessageContentImport 是 pkg.GameClient.Call 回调参数 *base.MessageContent 所在的包(robot/pkg/client.go)。
	robotMessageContentImport = "proto/common/base"

	// 模板里 Kind 的取值。
	robotRpcKindRequest = "REQUEST"
	robotRpcKindOneWay  = "ONE_WAY"
)

// robotRpcFixedNames 是产物里固定占用的标识符:固定 import 的包名,以及接收者、参数与局部变量名。
// proto 包的 import 别名避开它们,否则会撞名或在函数体里被遮蔽。
var robotRpcFixedNames = []string{
	"context", "fmt", "time", "proto", "pkg", "game",
	"r", "c", "req", "timeout", "done", "ctx", "reply", "err", "resp",
}

// robotRpcFile 是调用桩目录里的一个产物。
type robotRpcFile struct {
	Name    string
	Content []byte
}

// robotRpcServicePlan 是一个服务的生成计划(类型尚未带包限定)。
type robotRpcServicePlan struct {
	ProtoFile   string // proto/friend/friend.proto
	ServiceName string // proto service 名原样
	VarName     string // 导出的零值变量名 = ServiceName
	TypeName    string // 未导出的空结构类型名 = lowerCamel(ServiceName) + "Rpc"
	FileName    string // camelToSnake(ServiceName) + ".go"
	Methods     []robotRpcMethodPlan
}

// robotRpcMethodPlan 是一个 REQUEST / ONE_WAY 方法的生成计划。
type robotRpcMethodPlan struct {
	Kind           string // robotRpcKindRequest / robotRpcKindOneWay
	Name           string // proto 方法名
	MessageIDConst string // robot/generated/pb/game 里的消息号常量名 <Service><Method>MessageId
	Request        robotGoType
	Response       robotGoType // 只有 REQUEST
}

// robotRpcFileData 是 robot_rpc.go.tmpl 的数据;类型名都已带 import 别名。
type robotRpcFileData struct {
	ProtoFile          string
	ServiceName        string
	VarName            string
	TypeName           string
	HasRequest         bool   // 为 true 时模板才 import context / fmt / time / protobuf proto
	MessageContentType string // <别名>.MessageContent,只在 HasRequest 时使用
	Imports            []robotGoImport
	Methods            []robotRpcMethodData
}

// robotGoImport 是一条 proto 包 import,按 Path 升序排列。
type robotGoImport struct {
	Alias string
	Path  string
}

// robotRpcMethodData 是模板里的一个方法。
type robotRpcMethodData struct {
	Kind           string
	Name           string
	SyncName       string // <Name>Sync
	DecodeName     string // decode<Name>
	MessageIDConst string
	RequestType    string
	ResponseType   string
}

// GoRobotRpcGenerator 是流水线入口(FinalTasksAndOptionProcessing 组,须在 cppGen.InitMessageId 与描述符集解析之后)。
// 方法形态校验违例、命名冲突、类型无法映射、输出目录未配置都 Fatal;产物逐字节确定,内容不变不落盘。
func GoRobotRpcGenerator(wg *sync.WaitGroup) {
	wg.Add(1)
	go func() {
		defer wg.Done()

		services, err := internal.ClassifyClientRpcServices(internal.GlobalRPCServiceList, internal.IsSceneTCPMethod)
		if err != nil {
			logger.Global.Fatal("Client RPC method kinds failed validation", zap.Error(err))
			return
		}

		dir := _config.Global.Paths.RobotRpcDir
		if dir == "" {
			logger.Global.Fatal("robot_rpc_dir is not configured; add it to the paths section of proto_gen*.yaml")
			return
		}

		fileCount, err := generateRobotRpc(services, internal.FdSet.GetFile(), dir, robotRpcTemplatePath,
			_config.Global.Naming.MessageId)
		if err != nil {
			logger.Global.Fatal("Failed to generate robot RPC stubs",
				zap.String("dir", dir),
				zap.Error(err),
			)
			return
		}

		logger.Global.Info("Robot RPC stubs generated",
			zap.Int("file_count", fileCount),
			zap.String("dir", dir),
		)
	}()
}

// generateRobotRpc 渲染全部服务并整写 dir,返回生成的文件数。
// files 是描述符集里的全部文件(含依赖),用于把 proto 类型名映射成 Go 类型;messageIDSuffix 是
// naming.message_id(消息号常量名 = <Service><Method> + 它,与 internal.WriteGoMessageId 同源)。
func generateRobotRpc(services []internal.ClientRpcService, files []*descriptorpb.FileDescriptorProto,
	dir, templatePath, messageIDSuffix string) (int, error) {
	tmpl, err := template.ParseFiles(templatePath)
	if err != nil {
		return 0, fmt.Errorf("parse template %s: %w", templatePath, err)
	}
	outputs, err := renderRobotRpcFiles(services, newRobotGoTypeIndex(files), tmpl, messageIDSuffix)
	if err != nil {
		return 0, err
	}
	if err := writeRobotRpcDir(dir, outputs); err != nil {
		return 0, err
	}
	return len(outputs), nil
}

// renderRobotRpcFiles 把分类结果渲染成调用桩目录的全部文件(不碰磁盘)。服务按名排序处理,方法按 proto 声明顺序,
// 文件按文件名排序,输出逐字节确定。
// 错误(收集全部后返回):类型无法映射、消息号放不进 uint32、名字不可导出、同一类型上的方法名冲突(<Method> 与
// 另一个方法的 <Method>Sync 等)、两个服务映射到同一变量名 / 类型名 / 文件名(大小写不敏感:Windows 文件系统上会互相覆盖)。
func renderRobotRpcFiles(services []internal.ClientRpcService, types robotGoTypeIndex, tmpl *template.Template,
	messageIDSuffix string) ([]robotRpcFile, error) {
	ordered := append([]internal.ClientRpcService(nil), services...)
	sort.SliceStable(ordered, func(i, j int) bool {
		a, b := ordered[i].Service, ordered[j].Service
		if a.Service() != b.Service() {
			return a.Service() < b.Service()
		}
		return a.Fd.GetName() < b.Fd.GetName()
	})

	var (
		plans []robotRpcServicePlan
		errs  []error
	)
	varOwners := map[string]string{}  // 小写变量名 → 先占用它的服务(类型名由变量名推出,冲突与之等价)
	fileOwners := map[string]string{} // 小写文件名 → 先占用它的服务
	for _, service := range ordered {
		plan, err := planRobotRpcService(service, types, messageIDSuffix)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		if len(plan.Methods) == 0 {
			continue
		}
		owner := plan.ServiceName + " (" + plan.ProtoFile + ")"
		if previous, taken := varOwners[strings.ToLower(plan.VarName)]; taken {
			errs = append(errs, fmt.Errorf("services %s and %s both map to Go variable %s / type %s (case-insensitive); rename one of them",
				previous, owner, plan.VarName, plan.TypeName))
			continue
		}
		if previous, taken := fileOwners[strings.ToLower(plan.FileName)]; taken {
			errs = append(errs, fmt.Errorf("services %s and %s both map to file %s (case-insensitive); rename one of them",
				previous, owner, plan.FileName))
			continue
		}
		varOwners[strings.ToLower(plan.VarName)] = owner
		fileOwners[strings.ToLower(plan.FileName)] = owner
		plans = append(plans, plan)
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}

	// 包级声明(全部服务的变量与类型)与 import 别名同处一个作用域链,Go 不允许同名,所以一并保留。
	reserved := map[string]struct{}{}
	for _, name := range robotRpcFixedNames {
		reserved[name] = struct{}{}
	}
	for _, plan := range plans {
		reserved[plan.VarName] = struct{}{}
		reserved[plan.TypeName] = struct{}{}
	}

	files := make([]robotRpcFile, 0, len(plans))
	for _, plan := range plans {
		var content bytes.Buffer
		if err := tmpl.Execute(&content, plan.fileData(reserved)); err != nil {
			errs = append(errs, fmt.Errorf("render %s: %w", plan.FileName, err))
			continue
		}
		files = append(files, robotRpcFile{
			Name:    plan.FileName,
			Content: []byte(utils.NormalizeGeneratedLayout(content.String())),
		})
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Name < files[j].Name })
	return files, nil
}

// planRobotRpcService 生成一个服务的计划;PUSH / SERVER_ONLY 方法不产生成员。没有 REQUEST / ONE_WAY 方法时
// 返回空计划(调用方跳过,不出文件),此时不校验服务名。
func planRobotRpcService(service internal.ClientRpcService, types robotGoTypeIndex, messageIDSuffix string) (robotRpcServicePlan, error) {
	info := service.Service
	name := info.Service()
	plan := robotRpcServicePlan{
		ProtoFile:   filepath.ToSlash(info.Fd.GetName()),
		ServiceName: name,
		VarName:     name,
		TypeName:    lowerFirstRune(name) + "Rpc",
		FileName:    camelToSnake(name) + ".go",
	}

	var errs []error
	// Go 方法名 → 产生它的 proto 方法。Go 标识符区分大小写,这里按原样比较。
	memberOwners := map[string]string{}
	claim := func(member, owner string) {
		if previous, taken := memberOwners[member]; taken {
			errs = append(errs, fmt.Errorf("%s: Go method %s of %s collides with the one generated for %s; rename one of them",
				owner, member, plan.TypeName, previous))
			return
		}
		memberOwners[member] = owner
	}

	for _, classified := range service.Methods {
		var kind string
		switch classified.Kind {
		case internal.ClientRpcRequest:
			kind = robotRpcKindRequest
		case internal.ClientRpcOneWay:
			kind = robotRpcKindOneWay
		case internal.ClientRpcPush, internal.ClientRpcServerOnly:
			continue
		default:
			errs = append(errs, fmt.Errorf("%s.%s: unexpected client RPC kind %s", name, classified.Method.Method(), classified.Kind))
			continue
		}
		where := name + "." + classified.Method.Method()
		method, err := planRobotRpcMethod(classified.Method, kind, types, messageIDSuffix)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", where, err))
			continue
		}
		claim(method.Name, where)
		if kind == robotRpcKindRequest {
			claim(method.Name+"Sync", where)
			claim("decode"+method.Name, where)
		}
		plan.Methods = append(plan.Methods, method)
	}
	if len(errs) > 0 {
		return robotRpcServicePlan{}, errors.Join(errs...)
	}
	if len(plan.Methods) == 0 {
		return plan, nil
	}

	where := name + " (" + plan.ProtoFile + ")"
	if !token.IsExported(name) {
		return robotRpcServicePlan{}, fmt.Errorf("%s: service name must start with an upper-case letter so the robot stub variable is exported", where)
	}
	if err := checkRobotGoFileName(plan.FileName); err != nil {
		return robotRpcServicePlan{}, fmt.Errorf("%s: %w", where, err)
	}
	return plan, nil
}

// planRobotRpcMethod 生成一个方法的计划:REQUEST 取输入 / 输出类型(Empty 响应照常作响应类型:gRPC 路径的 Empty
// 响应同样回包),ONE_WAY 只取输入类型。
func planRobotRpcMethod(method *internal.MethodInfo, kind string, types robotGoTypeIndex, messageIDSuffix string) (robotRpcMethodPlan, error) {
	name := method.Method()
	if !token.IsExported(name) {
		return robotRpcMethodPlan{}, errors.New("method name must start with an upper-case letter so the robot stub is exported")
	}
	if method.Id > math.MaxUint32 {
		return robotRpcMethodPlan{}, fmt.Errorf("message id %d does not fit the uint32 message id of pkg.GameClient", method.Id)
	}
	key := method.KeyName()
	// internal.WriteGoMessageId 生成常量名时会把 "__" 折成 "_",这里引用的常量名就会对不上。
	if strings.Contains(key, "__") {
		return robotRpcMethodPlan{}, fmt.Errorf("message id constant %s%s would be renamed by internal.WriteGoMessageId (it collapses \"__\"); rename the service or method",
			key, messageIDSuffix)
	}

	request, err := types.resolve(method.MethodDescriptorProto.GetInputType())
	if err != nil {
		return robotRpcMethodPlan{}, err
	}
	plan := robotRpcMethodPlan{
		Kind:           kind,
		Name:           name,
		MessageIDConst: key + messageIDSuffix,
		Request:        request,
	}
	if kind == robotRpcKindRequest {
		plan.Response, err = types.resolve(method.MethodDescriptorProto.GetOutputType())
		if err != nil {
			return robotRpcMethodPlan{}, err
		}
	}
	return plan, nil
}

// fileData 分配 import 别名并给类型名加包限定。同一个包只 import 一次;REQUEST 还需要 MessageContent 所在的包。
func (plan robotRpcServicePlan) fileData(reserved map[string]struct{}) robotRpcFileData {
	var (
		importPaths []string
		hasRequest  bool
	)
	seen := map[string]struct{}{}
	use := func(importPath string) {
		if _, ok := seen[importPath]; ok {
			return
		}
		seen[importPath] = struct{}{}
		importPaths = append(importPaths, importPath)
	}
	for _, method := range plan.Methods {
		use(method.Request.ImportPath)
		if method.Kind == robotRpcKindRequest {
			hasRequest = true
			use(method.Response.ImportPath)
		}
	}
	if hasRequest {
		use(robotMessageContentImport)
	}
	sort.Strings(importPaths)
	aliases := robotImportAliases(importPaths, reserved)
	qualify := func(t robotGoType) string { return aliases[t.ImportPath] + "." + t.Name }

	data := robotRpcFileData{
		ProtoFile:   plan.ProtoFile,
		ServiceName: plan.ServiceName,
		VarName:     plan.VarName,
		TypeName:    plan.TypeName,
		HasRequest:  hasRequest,
	}
	if hasRequest {
		data.MessageContentType = aliases[robotMessageContentImport] + ".MessageContent"
	}
	for _, importPath := range importPaths {
		data.Imports = append(data.Imports, robotGoImport{Alias: aliases[importPath], Path: importPath})
	}
	for _, method := range plan.Methods {
		item := robotRpcMethodData{
			Kind:           method.Kind,
			Name:           method.Name,
			MessageIDConst: method.MessageIDConst,
			RequestType:    qualify(method.Request),
		}
		if method.Kind == robotRpcKindRequest {
			item.SyncName = method.Name + "Sync"
			item.DecodeName = "decode" + method.Name
			item.ResponseType = qualify(method.Response)
		}
		data.Methods = append(data.Methods, item)
	}
	return data
}

// writeRobotRpcDir 整写调用桩目录:写入本次全部文件,然后删除不在本次清单里的旧桩。只动 dir 这一层,不递归。
// 写入前先检查:目标文件已存在却不是本生成器的产物(手写文件与生成桩同名)时整次失败,一个文件都不写。
// 写入走 utils.WriteFileIfChanged,内容不变不落盘。
func writeRobotRpcDir(dir string, files []robotRpcFile) error {
	dir = filepath.Clean(dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", dir, err)
	}
	for _, file := range files {
		path := filepath.Join(dir, file.Name)
		content, err := os.ReadFile(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return fmt.Errorf("read %s: %w", path, err)
		}
		if !isGeneratedRobotRpcSource(content) {
			return fmt.Errorf("%s exists but was not generated by protogen; refusing to overwrite it (move the hand-written code to another file name)", path)
		}
	}

	// 文件名按小写比较:Windows 文件系统大小写不敏感,大小写不同的旧名就是本次写入的那个文件,不能删。
	// 代价:大小写敏感的文件系统(Linux)上,只差大小写的旧桩不会被清理,要手工删;服务改名只改大小写的情况极少。
	keep := make(map[string]struct{}, len(files))
	for _, file := range files {
		keep[strings.ToLower(file.Name)] = struct{}{}
		path := filepath.Join(dir, file.Name)
		if err := utils.WriteFileIfChanged(path, file.Content); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
	}
	return removeStaleRobotRpcFiles(dir, keep)
}

// removeStaleRobotRpcFiles 删除 dir 里不在 keep(小写文件名)中、以 robotRpcSourceMarker 开头的 .go;
// 别的文件只告警、不删。不递归子目录。
func removeStaleRobotRpcFiles(dir string, keep map[string]struct{}) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("list %s: %w", dir, err)
	}

	var errs []error
	for _, entry := range entries {
		name := entry.Name()
		if !entry.Type().IsRegular() || !strings.HasSuffix(name, ".go") {
			continue
		}
		if _, ok := keep[strings.ToLower(name)]; ok {
			continue
		}
		path := filepath.Join(dir, name)
		content, err := os.ReadFile(path)
		if err != nil {
			errs = append(errs, fmt.Errorf("read %s: %w", path, err))
			continue
		}
		if !isGeneratedRobotRpcSource(content) {
			logger.Global.Warn("Leaving a Go file not generated by protogen in the robot RPC directory",
				zap.String("file", path))
			continue
		}
		if err := os.Remove(path); err != nil {
			errs = append(errs, fmt.Errorf("remove %s: %w", path, err))
			continue
		}
		logger.Global.Info("Removed stale robot RPC stub", zap.String("file", path))
	}
	return errors.Join(errs...)
}

// isGeneratedRobotRpcSource 判断 .go 是否本生成器的产物(容忍检出时换成 CRLF 与 UTF-8 BOM)。
func isGeneratedRobotRpcSource(content []byte) bool {
	head := content
	if len(head) > 256 {
		head = head[:256]
	}
	text := strings.TrimPrefix(strings.ReplaceAll(string(head), "\r", ""), "\uFEFF")
	return strings.HasPrefix(text, robotRpcSourceMarker)
}
