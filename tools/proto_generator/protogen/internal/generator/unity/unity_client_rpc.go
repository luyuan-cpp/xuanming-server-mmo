const (
	// rpcTemplatePath 相对 protogen 根目录(生成器的工作目录)。
	rpcTemplatePath = "internal/template/unity_client_rpc.cs.tmpl"

	rpcClassSuffix = "Rpc"

	// rpcSourceMarker 是模板产物的开头,目录整写靠它认出本生成器的产物,既防删也防覆盖:只删除以它开头的旧 .cs;
	// 本次要写的 .cs 已存在却不以它开头(手写脚本与生成桩同名)时整次报错,一个文件都不写。unity_rpc_dir 误配到
	// 别的目录时,手写脚本与其它工具的产物(例如同级的 TipFaults.cs)既不会被当成旧桩删掉,也不会被同名产物覆盖。
	// 改模板头部时同步改这里。
	rpcSourceMarker = "// <auto-generated>\n//   Generated by protogen from "

	// metaGUIDSalt 是 .meta GUID 的前缀:GUID = md5(metaGUIDSalt + 相对 Assets 的路径)。
	metaGUIDSalt = "protogen:"

	// 模板里 Kind 的取值。
	rpcKindRequest = "REQUEST"
	rpcKindOneWay  = "ONE_WAY"
	rpcKindPush    = "PUSH"
)

// rpcFileData 是一个服务文件的模板数据。
type rpcFileData struct {
	ProtoFile   string // proto/friend/friend.proto
	ServiceName string // proto service 名原样
	ClassName   string // <ServiceName>Rpc
	Members     []rpcMemberData
}

// rpcMemberData 是一个方法生成的成员;类型名都是带 global:: 的 C# 全限定名。
type rpcMemberData struct {
	Kind           string   // rpcKindRequest / rpcKindOneWay / rpcKindPush
	CallName       string   // REQUEST / ONE_WAY 为方法名,PUSH 为 On<方法名>
	MessageIDConst string   // <方法名>MessageId
	MessageID      uint64   // 消息号,已校验能放进 C# uint
	Summary        []string // proto 前导注释,已做 XML 转义;为空则不写 <summary>
	RequestType    string   // REQUEST / ONE_WAY
	ResponseType   string   // REQUEST
	PayloadType    string   // PUSH:方法输入类型
}

// rpcFile 是 Rpc 目录里的一个 .cs 产物;同名 .meta 在写盘时按路径确定性生成。
type rpcFile struct {
	Name    string
	Content []byte
}

// rpcDirLayout 描述 Rpc 输出目录。
type rpcDirLayout struct {
	dir          string // 绝对路径,无末尾分隔符
	assetsRelDir string // 相对 Assets 的路径,'/' 分隔,例如 Scripts/Net/Generated/Rpc
}

// UnityClientRpcGenerator 是流水线入口(FinalTasksAndOptionProcessing 组,须在 cppGen.InitMessageId 与
// 描述符集解析之后)。方法形态校验总是执行,违例即 Fatal,与是否写客户端无关;
// enable_unity_client 为 false 时只校验、不写客户端仓。
func UnityClientRpcGenerator(wg *sync.WaitGroup) {
	wg.Add(1)
	go func() {
		defer wg.Done()

		services, err := internal.ClassifyClientRpcServices(internal.GlobalRPCServiceList, internal.IsSceneTCPMethod)
		if err != nil {
			logger.Global.Fatal("Client RPC method kinds failed validation", zap.Error(err))
			return
		}

		if !_config.Global.Generators.EnableUnityClient {
			logger.Global.Debug("Unity client generator disabled; client RPC kinds validated only")
			return
		}

		layout, err := newRpcDirLayout(_config.Global.Paths.UnityClientDir, _config.Global.Paths.UnityRpcDir)
		if err != nil {
			logger.Global.Fatal("Invalid Unity RPC output directory", zap.Error(err))
			return
		}

		fileCount, err := generateUnityClientRpc(services, internal.FdSet.GetFile(), layout, rpcTemplatePath)
		if err != nil {
			logger.Global.Fatal("Failed to generate Unity client RPC stubs",
				zap.String("dir", layout.dir),
				zap.Error(err),
			)
			return
		}

		logger.Global.Info("Unity client RPC stubs generated",
			zap.Int("file_count", fileCount),
			zap.String("dir", layout.dir),
		)
	}()
}

// newRpcDirLayout 校验并解析输出目录:rpcDir 必须位于 <unityClientDir>/Assets 之下(且不是 Assets 本身),
// 否则 .meta GUID 的路径口径无从谈起。
func newRpcDirLayout(unityClientDir, rpcDir string) (rpcDirLayout, error) {
	if unityClientDir == "" || rpcDir == "" {
		return rpcDirLayout{}, fmt.Errorf("unity_client_dir and unity_rpc_dir must both be set when enable_unity_client is true (got %q, %q)",
			unityClientDir, rpcDir)
	}
	assetsDir := filepath.Join(unityClientDir, "Assets")
	dir := filepath.Clean(rpcDir)
	rel, err := filepath.Rel(assetsDir, dir)
	if err != nil {
		return rpcDirLayout{}, fmt.Errorf("unity_rpc_dir %s is not under %s: %w", rpcDir, assetsDir, err)
	}
	rel = filepath.ToSlash(rel)
	if rel == "." || rel == ".." || strings.HasPrefix(rel, "../") {
		return rpcDirLayout{}, fmt.Errorf("unity_rpc_dir %s must be a directory inside %s", rpcDir, assetsDir)
	}
	return rpcDirLayout{dir: dir, assetsRelDir: rel}, nil
}

// assetGUID 返回 Rpc 目录下文件 name 的 .meta GUID。
func (layout rpcDirLayout) assetGUID(name string) string {
	return unityMetaGUID(layout.assetsRelDir + "/" + name)
}

// unityMetaGUID 是生成资源的确定性 GUID:md5("protogen:" + 相对 Assets 的路径) 的 32 位小写十六进制。
// 同一路径每次生成都得到同一个 GUID,Unity 不会因为重新生成而换 GUID、断开引用。
func unityMetaGUID(assetsRelPath string) string {
	sum := md5.Sum([]byte(metaGUIDSalt + filepath.ToSlash(assetsRelPath)))
	return hex.EncodeToString(sum[:])
}

// generateUnityClientRpc 渲染全部服务并整写 Rpc 目录,返回生成的 .cs 文件数。
// files 是描述符集里的全部文件(含依赖),用于把 proto 类型名映射成 C# 类型名。
func generateUnityClientRpc(services []internal.ClientRpcService, files []*descriptorpb.FileDescriptorProto,
	layout rpcDirLayout, templatePath string) (int, error) {
	tmpl, err := template.ParseFiles(templatePath)
	if err != nil {
		return 0, fmt.Errorf("parse template %s: %w", templatePath, err)
	}
	outputs, err := renderRpcFiles(services, newCSharpTypeIndex(files), tmpl)
	if err != nil {
		return 0, err
	}
	if err := writeRpcDir(layout, outputs); err != nil {
		return 0, err
	}
	return len(outputs), nil
}

// renderRpcFiles 把分类结果渲染成 Rpc 目录的全部 .cs(不碰磁盘)。
// 每个至少有一个非 SERVER_ONLY 方法的服务一个文件,成员按 proto 声明顺序,文件按文件名排序,输出逐字节确定。
// 错误(收集全部后返回):类型无法映射、消息号放不进 uint、两个服务映射到同一个类名(大小写不敏感,
// Windows 文件系统上会互相覆盖)、同一类里成员名冲突。
func renderRpcFiles(services []internal.ClientRpcService, types csharpTypeIndex, tmpl *template.Template) ([]rpcFile, error) {
	var (
		files []rpcFile
		errs  []error
	)
	owners := map[string]string{} // 小写类名 → 先占用它的服务
	for _, service := range services {
		data, err := buildRpcFileData(service, types)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		if len(data.Members) == 0 {
			continue
		}
		owner := data.ServiceName + " (" + data.ProtoFile + ")"
		classKey := strings.ToLower(data.ClassName)
		if previous, taken := owners[classKey]; taken {
			errs = append(errs, fmt.Errorf("services %s and %s both map to C# class %s; rename one of them",
				previous, owner, data.ClassName))
			continue
		}
		owners[classKey] = owner

		var content bytes.Buffer
		if err := tmpl.Execute(&content, data); err != nil {
			errs = append(errs, fmt.Errorf("render %s: %w", data.ClassName, err))
			continue
		}
		files = append(files, rpcFile{
			Name:    data.ClassName + ".cs",
			Content: []byte(utils.NormalizeGeneratedLayout(content.String())),
		})
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Name < files[j].Name })
	return files, nil
}

// buildRpcFileData 生成一个服务的模板数据;SERVER_ONLY 方法不产生成员。
func buildRpcFileData(service internal.ClientRpcService, types csharpTypeIndex) (rpcFileData, error) {
	info := service.Service
	data := rpcFileData{
		ProtoFile:   filepath.ToSlash(info.Fd.GetName()),
		ServiceName: info.Service(),
		ClassName:   info.Service() + rpcClassSuffix,
	}

	var errs []error
	// C# 成员名 → 产生它的方法;类名本身也占位(CS0542:成员不得与所在类型同名)。
	memberOwners := map[string]string{data.ClassName: "the class name"}
	claim := func(member, owner string) {
		if previous, taken := memberOwners[member]; taken {
			errs = append(errs, fmt.Errorf("%s: C# member %s in class %s collides with %s",
				owner, member, data.ClassName, previous))
			return
		}
		memberOwners[member] = owner
	}

	for _, classified := range service.Methods {
		if classified.Kind == internal.ClientRpcServerOnly {
			continue
		}
		where := info.Service() + "." + classified.Method.Method()
		member, err := buildRpcMember(classified, types)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", where, err))
			continue
		}
		claim(member.MessageIDConst, where)
		claim(member.CallName, where)
		data.Members = append(data.Members, member)
	}
	if len(errs) > 0 {
		return rpcFileData{}, errors.Join(errs...)
	}
	return data, nil
}

// buildRpcMember 按形态生成一个成员:REQUEST 取输入 / 输出类型(Empty 响应照常作 TResp:gRPC 路径的 Empty
// 响应同样回包),ONE_WAY 只取输入类型,PUSH 的载荷是输入类型。
func buildRpcMember(classified internal.ClientRpcMethod, types csharpTypeIndex) (rpcMemberData, error) {
	method := classified.Method
	if method.Id > math.MaxUint32 {
		return rpcMemberData{}, fmt.Errorf("message id %d does not fit a C# uint constant", method.Id)
	}
	member := rpcMemberData{
		MessageIDConst: method.Method() + "MessageId",
		MessageID:      method.Id,
		Summary:        escapeXMLDocLines(internal.MethodLeadingComments(method)),
	}

	input, err := types.resolve(method.MethodDescriptorProto.GetInputType())
	if err != nil {
		return rpcMemberData{}, err
	}
	switch classified.Kind {
	case internal.ClientRpcRequest:
		output, err := types.resolve(method.MethodDescriptorProto.GetOutputType())
		if err != nil {
			return rpcMemberData{}, err
		}
		member.Kind = rpcKindRequest
		member.CallName = method.Method()
		member.RequestType = input
		member.ResponseType = output
	case internal.ClientRpcOneWay:
		member.Kind = rpcKindOneWay
		member.CallName = method.Method()
		member.RequestType = input
	case internal.ClientRpcPush:
		member.Kind = rpcKindPush
		member.CallName = "On" + method.Method()
		member.PayloadType = input
	default:
		return rpcMemberData{}, fmt.Errorf("unexpected client RPC kind %s", classified.Kind)
	}
	return member, nil
}

var xmlDocEscaper = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;")

// escapeXMLDocLines 转义写进 /// 文档注释的文本:注释里的 <、>、& 会被 C# 编译器当成 XML。
func escapeXMLDocLines(lines []string) []string {
	if len(lines) == 0 {
		return nil
	}
	escaped := make([]string, len(lines))
	for i, line := range lines {
		escaped[i] = xmlDocEscaper.Replace(line)
	}
	return escaped
}

// writeRpcDir 整写 Rpc 目录:写入本次全部 .cs 与确定性 .meta、目录自身的 Rpc.meta,然后删除不在本次清单里的旧桩。
// 写入前先检查:目标 .cs 已存在却不是本生成器的产物(手写脚本与生成桩同名)时整次失败,一个文件都不写
// (同 robot 的 writeRobotRpcDir)。写入走 utils.WriteFileIfChanged,内容不变不落盘;只动 layout.dir 这一层与它旁边的 Rpc.meta。
func writeRpcDir(layout rpcDirLayout, files []rpcFile) error {
	for _, file := range files {
		path := filepath.Join(layout.dir, file.Name)
		content, err := os.ReadFile(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return fmt.Errorf("read %s: %w", path, err)
		}
		if !isGeneratedRpcSource(content) {
			return fmt.Errorf("%s exists but was not generated by protogen; refusing to overwrite it (move the hand-written script to another file name)", path)
		}
	}

	if err := os.MkdirAll(layout.dir, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", layout.dir, err)
	}
	// 文件名按小写比较:Windows 文件系统大小写不敏感,服务名只改了大小写时,大小写不同的旧名就是本次写入的那个文件,不能删。
	// 代价:大小写敏感的文件系统(Linux)上,只差大小写的旧桩(连同它的 .meta)不会被清理,要手工删;服务改名只改大小写的情况极少。
	keep := make(map[string]struct{}, len(files))
	for _, file := range files {
		keep[strings.ToLower(file.Name)] = struct{}{}
		path := filepath.Join(layout.dir, file.Name)
		if err := utils.WriteFileIfChanged(path, file.Content); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
		if err := utils.WriteFileIfChanged(path+".meta", scriptMeta(layout.assetGUID(file.Name))); err != nil {
			return fmt.Errorf("write %s.meta: %w", path, err)
		}
	}
	folderMetaPath := layout.dir + ".meta"
	if err := utils.WriteFileIfChanged(folderMetaPath, folderMeta(unityMetaGUID(layout.assetsRelDir))); err != nil {
		return fmt.Errorf("write %s: %w", folderMetaPath, err)
	}
	return removeStaleRpcFiles(layout, keep)
}

// removeStaleRpcFiles 删除 Rpc 目录里不在 keep(小写文件名)中的旧桩:以 rpcSourceMarker 开头的 .cs 连同它的 .meta;
// 以及源文件已不存在、GUID 正是本生成器按该路径算出来的孤立 .meta。别的文件只告警、不删。不递归子目录。
// 两轮都按小写文件名查 keep 与 removed,理由同 writeRpcDir。
func removeStaleRpcFiles(layout rpcDirLayout, keep map[string]struct{}) error {
	entries, err := os.ReadDir(layout.dir)
	if err != nil {
		return fmt.Errorf("list %s: %w", layout.dir, err)
	}

	var errs []error
	removed := map[string]struct{}{} // 小写 .cs 文件名
	for _, entry := range entries {
		name := entry.Name()
		if !entry.Type().IsRegular() || !strings.HasSuffix(name, ".cs") {
			continue
		}
		if _, ok := keep[strings.ToLower(name)]; ok {
			continue
		}
		path := filepath.Join(layout.dir, name)
		content, err := os.ReadFile(path)
		if err != nil {
			errs = append(errs, fmt.Errorf("read %s: %w", path, err))
			continue
		}
		if !isGeneratedRpcSource(content) {
			logger.Global.Warn("Leaving a C# file not generated by protogen in the Unity RPC directory",
				zap.String("file", path))
			continue
		}
		if err := os.Remove(path); err != nil {
			errs = append(errs, fmt.Errorf("remove %s: %w", path, err))
			continue
		}
		if err := os.Remove(path + ".meta"); err != nil && !os.IsNotExist(err) {
			errs = append(errs, fmt.Errorf("remove %s.meta: %w", path, err))
		}
		removed[strings.ToLower(name)] = struct{}{}
		logger.Global.Info("Removed stale Unity RPC stub", zap.String("file", path))
	}

	for _, entry := range entries {
		name := entry.Name()
		if !entry.Type().IsRegular() || !strings.HasSuffix(name, ".cs.meta") {
			continue
		}
		source := strings.TrimSuffix(name, ".meta")
		if _, ok := keep[strings.ToLower(source)]; ok {
			continue
		}
		if _, ok := removed[strings.ToLower(source)]; ok {
			continue
		}
		_, statErr := os.Stat(filepath.Join(layout.dir, source))
		if statErr == nil {
			continue // 源文件还在(不是本生成器的产物),.meta 归它
		}
		if !os.IsNotExist(statErr) {
			errs = append(errs, fmt.Errorf("stat %s: %w", source, statErr))
			continue
		}
		path := filepath.Join(layout.dir, name)
		content, err := os.ReadFile(path)
		if err != nil {
			errs = append(errs, fmt.Errorf("read %s: %w", path, err))
			continue
		}
		if metaGUID(content) != layout.assetGUID(source) {
			logger.Global.Warn("Leaving an orphan .meta not generated by protogen in the Unity RPC directory",
				zap.String("file", path))
			continue
		}
		if err := os.Remove(path); err != nil {
			errs = append(errs, fmt.Errorf("remove %s: %w", path, err))
			continue
		}
		logger.Global.Info("Removed orphan Unity RPC stub meta", zap.String("file", path))
	}
	return errors.Join(errs...)
}

// isGeneratedRpcSource 判断 .cs 是否本生成器的产物(容忍检出时换成 CRLF 与 UTF-8 BOM)。
func isGeneratedRpcSource(content []byte) bool {
	head := content
	if len(head) > 256 {
		head = head[:256]
	}
	text := strings.TrimPrefix(strings.ReplaceAll(string(head), "\r", ""), "\ufeff")
	return strings.HasPrefix(text, rpcSourceMarker)
}

// metaGUID 取 .meta 里 guid 行的值;没有则返回空串。
func metaGUID(content []byte) string {
	for _, line := range strings.Split(strings.ReplaceAll(string(content), "\r", ""), "\n") {
		if value, ok := strings.CutPrefix(line, "guid: "); ok {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

// scriptMeta 是脚本 .meta,格式照客户端仓 Assets/Scripts/Net/RpcStatus.cs.meta(LF,冒号后保留 Unity 写的空格)。
func scriptMeta(guid string) []byte {
	return []byte("fileFormatVersion: 2\n" +
		"guid: " + guid + "\n" +
		"MonoImporter:\n" +
		"  externalObjects: {}\n" +
		"  serializedVersion: 2\n" +
		"  defaultReferences: []\n" +
		"  executionOrder: 0\n" +
		"  icon: {instanceID: 0}\n" +
		"  userData: \n" +
		"  assetBundleName: \n" +
		"  assetBundleVariant: \n")
}

// folderMeta 是目录 .meta,格式照客户端仓 Assets/Scripts/Net/Generated.meta。
func folderMeta(guid string) []byte {
	return []byte("fileFormatVersion: 2\n" +
		"guid: " + guid + "\n" +
		"folderAsset: yes\n" +
		"DefaultImporter:\n" +
		"  externalObjects: {}\n" +
		"  userData: \n" +
		"  assetBundleName: \n" +
		"  assetBundleVariant: \n")
}
