// Package unity 为 Unity 客户端生成类型化调用桩:每个客户端协议服务一个静态类
// Assets/Scripts/Net/Generated/Rpc/<Service>Rpc.cs(docs/design/client-rpc-callback.md §5.3)。
// 请求-响应方法带 RpcDone<TResp> 回调,单向方法只发,推送方法生成类型化注册函数;产物只依赖客户端的 IRpcChannel。
