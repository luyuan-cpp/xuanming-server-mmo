func readManifests(t *testing.T, root string, manifests map[string]string) map[string]string {
	t.Helper()
	current := make(map[string]string, len(manifests))
	for rel := range manifests {
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			t.Fatal(err)
		}
		current[rel] = string(body)
	}
	return current
}

func TestSyncThenRetireLeavesNoDanglingProjectEntries(t *testing.T) {
	root := useRetireConfig(t)
	manifests := protoManifestFixture()
	writeRepoFiles(t, root, manifests)
	writeRepoFiles(t, root, map[string]string{
		"proto/db/db.proto":       "syntax = \"proto3\";\n",
		"proto/login/login.proto": "syntax = \"proto3\";\n",
	})
	live := map[string]string{
		"cpp/generated/proto/db/db.pb.cc":                       cppOutput("db/db"),
		"cpp/generated/proto/db/db.pb.h":                        cppOutput("db/db"),
		"cpp/generated/proto/custom/handwritten.pb.cc":          "// 手写\n",
		"cpp/generated/grpc_client/grpc_init_client.cpp":        "// 聚合入口\n",
		"cpp/generated/grpc_client/login/login_grpc_client.cpp": grpcClientSourceBody,
		"cpp/generated/grpc_client/login/login_grpc_client.h":   grpcClientHeaderBody,
	}
	retired := map[string]string{
		"cpp/generated/proto/db/db_task.pb.cc":                cppOutput("db/db_task"),
		"cpp/generated/proto/db/db_task.pb.h":                 cppOutput("db/db_task"),
		"cpp/generated/grpc_client/gone/only_grpc_client.cpp": grpcClientSourceBody,
		"cpp/generated/grpc_client/gone/only_grpc_client.h":   grpcClientHeaderBody,
	}
	writeRepoFiles(t, root, live)
	writeRepoFiles(t, root, retired)

	if err := syncCppBuildProjects(_config.Global.Paths.ProtoDir, root); err != nil {
		t.Fatal(err)
	}
	afterSync := readManifests(t, root, manifests)
	for rel, text := range afterSync {
		normalized := strings.ReplaceAll(text, "\\", "/")
		for _, forbidden := range []string{"db_task", "ghost", "only_grpc_client"} {
			if strings.Contains(normalized, forbidden) {
				t.Errorf("%s 仍引用退役条目 %s:\n%s", rel, forbidden, text)
			}
		}
	}
	for rel, want := range map[string]string{
		"cpp/generated/proto/CMakeLists.txt":                    "custom/handwritten.pb.cc",
		"cpp/generated/proto/proto.vcxproj":                     "custom/handwritten.pb.cc",
		"cpp/generated/proto/proto.vcxproj.filters":             "custom/handwritten.pb.cc",
		"cpp/generated/grpc_client/CMakeLists.txt":              "login/login_grpc_client.cpp",
		"cpp/generated/grpc_client/grpc_client.vcxproj":         "login/login_grpc_client.h",
		"cpp/generated/grpc_client/grpc_client.vcxproj.filters": "login/login_grpc_client.h",
	} {
		if !strings.Contains(strings.ReplaceAll(afterSync[rel], "\\", "/"), want) {
			t.Errorf("%s 丢了不该动的条目 %s:\n%s", rel, want, afterSync[rel])
		}
	}
	// 文件留给下一步:清单校验失败时不能已经删了文件。
	assertRepoFilesKept(t, root, retired)

	for round := 1; round <= 2; round++ {
		if err := retireOrphanedOutputs(_config.Global.Paths.ProtoDir, orphanRetirementRules()); err != nil {
			t.Fatalf("第 %d 轮清退失败: %v", round, err)
		}
		assertRepoFilesGone(t, root, retired)
		assertRepoFilesKept(t, root, live)
		if err := syncCppBuildProjects(_config.Global.Paths.ProtoDir, root); err != nil {
			t.Fatalf("第 %d 轮同步失败: %v", round, err)
		}
		for rel, text := range readManifests(t, root, manifests) {
			if text != afterSync[rel] {
				t.Errorf("第 %d 轮后 %s 变了,同步不幂等:\n%s", round, rel, text)
			}
		}
	}
}

