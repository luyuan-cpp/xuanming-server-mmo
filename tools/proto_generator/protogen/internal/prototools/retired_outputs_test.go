func TestRetireOrphanedOutputsPrintsWholePlanBeforeDeleting(t *testing.T) {
	root := useRetireConfig(t)
	retired, kept := retireFixture()
	writeRepoFiles(t, root, retired)
	writeRepoFiles(t, root, kept)
	core, logs := observer.New(zapcore.WarnLevel)
	logger.Global = zap.New(core, zap.Hooks(func(entry zapcore.Entry) error {
		if entry.Message != retireLogMessage {
			return nil
		}
		for rel := range retired {
			if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel))); err != nil {
				t.Errorf("打印清单时 %s 已经被删了: %v", rel, err)
			}
		}
		return nil
	}))

	if err := retireOrphanedOutputs(_config.Global.Paths.ProtoDir, orphanRetirementRules()); err != nil {
		t.Fatal(err)
	}
	entries := logs.FilterMessage(retireLogMessage).All()
	if len(entries) != 1 {
		t.Fatalf("整张清单应该打成一条日志,实际 %d 条", len(entries))
	}
	files, ok := entries[0].ContextMap()["files"].([]interface{})
	if !ok {
		t.Fatalf("清单日志缺 files 字段: %v", entries[0].ContextMap())
	}
	printed := make(map[string]bool)
	for _, file := range files {
		rel, err := filepath.Rel(root, fmt.Sprint(file))
		if err != nil {
			t.Fatal(err)
		}
		printed[filepath.ToSlash(rel)] = true
	}
	for rel := range retired {
		if !printed[rel] {
			t.Errorf("清单漏了 %s", rel)
		}
	}
	if len(printed) != len(retired) {
		t.Errorf("清单多列了文件: 打印 %d 个,应为 %d 个: %v", len(printed), len(retired), printed)
	}

	logs.TakeAll()
	if err := retireOrphanedOutputs(_config.Global.Paths.ProtoDir, orphanRetirementRules()); err != nil {
		t.Fatal(err)
	}
	if count := logs.FilterMessage(retireLogMessage).Len(); count != 0 {
		t.Errorf("没有退役产物时不该打印清单,实际 %d 条", count)
	}
}

