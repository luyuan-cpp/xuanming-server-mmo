// 文件头照抄实际生成物(protoc 7.35)。licensedGoHeader 对应 go/proto/common/base/empty.pb.go:
// proto 文件的版权注释排在生成标记之前,标记之前的 source 字样不算数。
const (
	cppOutputHeader  = "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n// NO CHECKED-IN PROTOBUF GENCODE\n// source: proto/%s.proto\n// Protobuf C++ Version: 7.35.1\n\n#include <algorithm>\n"
	goOutputHeader   = "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.10\n// \tprotoc        v7.35.1\n// source: proto/%s.proto\n\npackage x\n"
	goGrpcHeader     = "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n// versions:\n// - protoc-gen-go-grpc v1.6.0\n// - protoc             v7.35.0\n// source: proto/%s.proto\n\npackage x\n"
	licensedGoHeader = "// Protocol Buffers - Google's data interchange format\n// source: proto/not/the/real/source.proto\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.10\n// source: proto/%s.proto\n\npackage base\n"

	grpcClientHeaderBody = "#pragma once\n#include <chrono>\n#include \"core/network/grpc_client_call.h\"\n"
	grpcClientSourceBody = "#include \"muduo/base/Logging.h\"\n\n#include \"core/network/grpc_client_runtime.h\"\n"
)

func cppOutput(stem string) string    { return fmt.Sprintf(cppOutputHeader, stem) }
func goOutput(stem string) string     { return fmt.Sprintf(goOutputHeader, stem) }
func goGrpcOutput(stem string) string { return fmt.Sprintf(goGrpcHeader, stem) }
func licensedGoOutput(stem string) string {
	return fmt.Sprintf(licensedGoHeader, stem)
}
func stagedProto(goPackage string) string {
	return "syntax = \"proto3\";\noption go_package = \"" + goPackage + "\";\n\nmessage Placeholder {}\n"
}

// useRetireConfig 让生成器配置指向临时仓库,返回仓库根。路径形状与 proto_gen.yaml 解析后一致。
func useRetireConfig(t *testing.T) string {
	t.Helper()
	previousConfig := _config.Global
	previousLogger := logger.Global
	logger.Global = zap.NewNop()
	t.Cleanup(func() {
		_config.Global = previousConfig
		logger.Global = previousLogger
	})
	root := t.TempDir()
	separator := string(os.PathSeparator)
	_config.Global.Paths.OutputRoot = root + separator
	_config.Global.Paths.ProtoDir = filepath.Join(root, "proto") + separator
	_config.Global.Paths.NodeGoDir = filepath.Join(root, "go") + separator
	_config.Global.Paths.GeneratorProtoDir = filepath.Join(root, "generated", "proto") + separator
	_config.Global.Paths.RobotGeneratedProto = filepath.Join(root, "generated", "robot", "proto") + separator
	_config.Global.DirectoryNames.NormalGoProto = "proto"
	_config.Global.Naming.GoRobotPackage = "robot"
	_config.Global.Generators.EnableCpp = true
	_config.Global.Generators.EnableRobotProto = true
	return root
}

func writeRepoFiles(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, body := range files {
		file := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(file), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(file, []byte(body), 0644); err != nil {
			t.Fatal(err)
		}
	}
}

func assertRepoFilesKept(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, body := range files {
		actual, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			t.Errorf("不该清退的文件 %s 没了: %v", rel, err)
			continue
		}
		if string(actual) != body {
			t.Errorf("不该清退的文件 %s 被改了: %q", rel, actual)
		}
	}
}

func assertRepoFilesGone(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel := range files {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel))); !os.IsNotExist(err) {
			t.Errorf("退役产物 %s 仍在: %v", rel, err)
		}
	}
}

