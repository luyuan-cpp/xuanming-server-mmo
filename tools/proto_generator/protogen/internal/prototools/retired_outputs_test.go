func TestRemoveRetiredEntriesKeepsOtherEntriesAndIsIdempotent(t *testing.T) {
	retired := func(entry string) (bool, error) {
		return strings.HasPrefix(entry, "db/db_task."), nil
	}
	for name, text := range map[string]string{
		"CMakeLists.txt":        "# 保留配置\r\nset(SOURCE_FILES\r\n    db/db.pb.cc\r\n    db/db_task.pb.cc\r\n)\r\nadd_library(proto STATIC ${SOURCE_FILES})\r\n",
		"proto.vcxproj":         "<Project>\r\n  <ItemGroup>\r\n    <ClCompile Include=\"db\\db.pb.cc\" />\r\n    <ClCompile Include=\"db\\db_task.pb.cc\" />\r\n    <ClInclude Include=\"db\\db_task.pb.h\" />\r\n  </ItemGroup>\r\n</Project>\r\n",
		"proto.vcxproj.filters": "<Project>\n  <ItemGroup>\n    <ClCompile Include=\"db\\db.pb.cc\">\n      <Filter>源文件</Filter>\n    </ClCompile>\n    <ClCompile Include=\"db\\db_task.pb.cc\">\n      <Filter>源文件</Filter>\n    </ClCompile>\n  </ItemGroup>\n</Project>\n",
	} {
		t.Run(name, func(t *testing.T) {
			got, removed, err := removeRetiredEntries(name, text, retired)
			if err != nil {
				t.Fatal(err)
			}
			if len(removed) == 0 || strings.Contains(got, "db_task") {
				t.Fatalf("退役条目没有清掉: removed=%v\n%s", removed, got)
			}
			if !strings.Contains(got, "db.pb.cc") {
				t.Fatalf("还在的条目不能动:\n%s", got)
			}
			if !strings.HasPrefix(got, strings.SplitN(text, "\n", 2)[0]) {
				t.Fatalf("破坏了工程配置:\n%s", got)
			}
			again, removedAgain, err := removeRetiredEntries(name, got, retired)
			if err != nil || again != got || len(removedAgain) != 0 {
				t.Fatalf("重复运行必须幂等: removed=%v err=%v\n%s", removedAgain, err, again)
			}
		})
	}
}

