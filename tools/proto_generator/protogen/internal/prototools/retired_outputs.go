const (
	// protoSourcePrefix 是 protoc 产物头部 "// source:" 行的路径前缀:C++ 与 Go 都让源路径从 proto/ 开始。
	protoSourcePrefix = "proto/"
	// outputHeadLimit 是判定产物来源时读取的文件头长度。标记都在文件开头,
	// 但 Go 产物前面可能带 proto 文件的版权注释(go/proto/common/base/empty.pb.go),不能只看第一行。
	outputHeadLimit = 64 << 10
	// retireLogMessage 是打印清单那条日志的消息,验收时按它检索。
	retireLogMessage = "Retiring generated outputs whose source proto no longer exists"
)

// outputState 是一个产物相对源 proto 的状态。
type outputState int

const (
	// outputLive:源 proto 还在,或者这个文件不是这类产物。
	outputLive outputState = iota
	// outputRetired:源 proto 已删除,且能证明文件出自生成流程。
	outputRetired
	// outputUnproven:名字像产物、对应的源不在,但文件头证明不了来源。只告警,不删文件也不动工程条目。
	outputUnproven
)

// protoOutputKind 描述一类由 proto 派生的产物:怎样从路径推出候选源,怎样从文件头证明来源。
type protoOutputKind struct {
	// suffixes 是产物后缀,去掉后缀加 .proto 就是候选源。一个文件可能匹配多个后缀:
	// x_grpc.pb.go 既可能是 x.proto 的 gRPC 桩,也可能是 x_grpc.proto 的消息绑定
	// (proto/common/constants/etcd_grpc.proto 就是后者),所以路径只给候选,以文件头写明的源为准。
	suffixes []string
	// declaredSource 从文件头取产物声明的源(相对 proto 根、正斜杠)。不是生成流程的产物返回 false。
	declaredSource func(rel string, head []byte) (string, bool)
}

var (
	cppMessageOutput = protoOutputKind{
		suffixes:       []string{".pb.cc", ".pb.h"},
		declaredSource: protocDeclaredSource("// Generated by the protocol buffer compiler.  DO NOT EDIT!"),
	}
	goBindingOutput = protoOutputKind{
		suffixes: []string{"_grpc.pb.go", ".pb.go"},
		declaredSource: protocDeclaredSource(
			"// Code generated by protoc-gen-go. DO NOT EDIT.",
			"// Code generated by protoc-gen-go-grpc. DO NOT EDIT."),
	}
	cppGrpcClientOutput = protoOutputKind{
		suffixes:       []string{"_grpc_client.cpp", "_grpc_client.h"},
		declaredSource: grpcClientDeclaredSource,
	}

	// C++ gRPC 调用适配器的模板没有生成标记,只能按模板固定写出的 include 认。
	// 模板改掉这两行时认不出就只告警不删;TestGrpcClientFingerprintsMatchTemplates 会先失败。
	grpcClientFingerprints = map[string]string{
		"_grpc_client.h":   `#include "core/network/grpc_client_call.h"`,
		"_grpc_client.cpp": `#include "core/network/grpc_client_runtime.h"`,
	}

	// cppManagedProjects 是工程清单由生成器维护、产物按 proto 派生的 C++ 工程。
	cppManagedProjects = []struct {
		name string
		kind protoOutputKind
	}{{"proto", cppMessageOutput}, {"grpc_client", cppGrpcClientOutput}}
)

// protocDeclaredSource 取 protoc 产物头部生成标记之后的第一个 "// source:" 行。
// 标记之前的注释是 proto 文件自己的版权声明,里面的内容不算数。
func protocDeclaredSource(markers ...string) func(string, []byte) (string, bool) {
	return func(_ string, head []byte) (string, bool) {
		marked := false
		for _, line := range strings.Split(strings.TrimPrefix(string(head), "\uFEFF"), "\n") {
			line = strings.TrimRight(line, " \t\r")
			if line == "" {
				continue
			}
			if !strings.HasPrefix(line, "//") {
				return "", false
			}
			if !marked {
				marked = slices.Contains(markers, line)
				continue
			}
			if source, ok := strings.CutPrefix(line, "// source: "); ok {
				return strings.CutPrefix(source, protoSourcePrefix)
			}
		}
		return "", false
	}
}

func grpcClientDeclaredSource(rel string, head []byte) (string, bool) {
	for suffix, fingerprint := range grpcClientFingerprints {
		if stem, ok := strings.CutSuffix(rel, suffix); ok && bytes.Contains(head, []byte(fingerprint)) {
			return stem + ".proto", true
		}
	}
	return "", false
}

// stagedProtoOutput 是 CopyProtoToGenDir 复制、AddGoPackageToProtoDir 盖过 go_package 的暂存副本。
// 这些目录是 proto/ 的镜像,AGENTS §3 不许手改;go_package 行与所在位置对得上,说明它走过暂存流程。
func stagedProtoOutput(goPackageBase string) protoOutputKind {
	return protoOutputKind{
		suffixes: []string{".proto"},
		declaredSource: func(rel string, head []byte) (string, bool) {
			// 与 generator/go 的 GenGoPackageOptWithPkg 写出的一行相同。
			want := fmt.Sprintf("option go_package = \"%s\";", path.Join(goPackageBase, protoSourcePrefix, path.Dir(rel)))
			for _, line := range strings.Split(string(head), "\n") {
				if strings.TrimSpace(line) == want {
					return rel, true
				}
			}
			return "", false
		},
	}
}

// candidateSources 从产物路径(正斜杠)推出候选源。不是这类产物时返回空。
func (kind protoOutputKind) candidateSources(rel string) []string {
	var candidates []string
	for _, suffix := range kind.suffixes {
		stem, ok := strings.CutSuffix(rel, suffix)
		if ok && stem != "" && !strings.HasSuffix(stem, "/") {
			candidates = append(candidates, stem+".proto")
		}
	}
	return candidates
}

// classify 判定 root 下的 rel(正斜杠)是否退役产物。工程条目也走这里,条目指向的文件可能已经不在。
func (kind protoOutputKind) classify(protoRoot, root, rel string) (outputState, error) {
	candidates := kind.candidateSources(rel)
	if len(candidates) == 0 || !filepath.IsLocal(filepath.FromSlash(rel)) {
		return outputLive, nil
	}
	existing := 0
	for _, candidate := range candidates {
		exists, err := protoSourceExists(protoRoot, candidate)
		if err != nil {
			return outputLive, err
		}
		if exists {
			existing++
		}
	}
	if existing == len(candidates) {
		return outputLive, nil
	}
	head, err := readOutputHead(filepath.Join(root, filepath.FromSlash(rel)))
	if os.IsNotExist(err) {
		// 只有工程条目会走到这里:文件已经没了,候选源也都不在,这条登记没有任何东西可指。
		if existing == 0 {
			return outputRetired, nil
		}
		return outputLive, nil
	}
	if err != nil {
		return outputLive, err
	}
	declared, ok := kind.declaredSource(rel, head)
	if !ok || !slices.Contains(candidates, declared) {
		return outputUnproven, nil
	}
	exists, err := protoSourceExists(protoRoot, declared)
	if err != nil {
		return outputLive, err
	}
	if exists {
		return outputLive, nil
	}
	return outputRetired, nil
}

func protoSourceExists(protoRoot, source string) (bool, error) {
	_, err := os.Stat(filepath.Join(protoRoot, filepath.FromSlash(source)))
	if err == nil {
		return true, nil
	}
	if os.IsNotExist(err) {
		return false, nil
	}
	return false, err
}

func readOutputHead(file string) ([]byte, error) {
	reader, err := os.Open(file)
	if err != nil {
		return nil, err
	}
	defer reader.Close()
	return io.ReadAll(io.LimitReader(reader, outputHeadLimit))
}

// hasProtoSources 报告源目录里是否有 .proto。源目录缺失或为空时,所有产物都会被判成「源已不存在」,不能往下走。
func hasProtoSources(protoRoot string) (bool, error) {
	found := false
	err := filepath.WalkDir(protoRoot, func(file string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if utils.IsProtoFile(entry) {
			found = true
			return fs.SkipAll
		}
		return nil
	})
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return found, err
}

// retireRule 是一个输出目录的清退规则。清退只在 root 之内发生。
type retireRule struct {
	root string
	kind protoOutputKind
}

// orphanRetirementRules 列出会留下退役产物的输出目录,路径与写入方一致。
//
// 不在此列的两处:generated/proto/_unified 每次整目录重建;tools/generated/temp 是 protoc 的临时输出,
// CopyCppOutputs 只按当前协议列表读取,残留不会被发布。
func orphanRetirementRules() []retireRule {
	paths := _config.Global.Paths
	var rules []retireRule
	// 工程清单只在启用 C++ 时同步,没同步就删文件,工程会找不到源。
	if _config.Global.Generators.EnableCpp {
		for _, project := range cppManagedProjects {
			rules = append(rules, retireRule{filepath.Join(paths.OutputRoot, "cpp", "generated", project.name), project.kind})
		}
	}
	rules = append(rules,
		retireRule{filepath.Join(paths.NodeGoDir, "proto"), goBindingOutput},
		// robot 用 -mod=vendor 构建,这里是 go/proto 的副本。这一步只删不补:新协议进 vendor 仍靠 go mod vendor。
		retireRule{filepath.Join(paths.OutputRoot, "robot", "vendor", "proto"), goBindingOutput},
	)
	for _, service := range goctlServices {
		rules = append(rules, retireRule{paths.GeneratorProtoDir + BuildGeneratorProtoPath(service), stagedProtoOutput(service)})
	}
	if _config.Global.Generators.EnableRobotProto {
		rules = append(rules, retireRule{paths.RobotGeneratedProto, stagedProtoOutput(_config.Global.Naming.GoRobotPackage)})
	}
	return rules
}

// RetireOrphanedOutputs 清退源 proto 已删除的生成产物。必须排在 SyncCppBuildProjects 之后:
// 工程清单校验失败时那一步直接终止,文件不会先于清单被删。
func RetireOrphanedOutputs(wg *sync.WaitGroup) {
	wg.Add(1)
	defer wg.Done()
	if err := retireOrphanedOutputs(_config.Global.Paths.ProtoDir, orphanRetirementRules()); err != nil {
		logger.Global.Fatal("Failed to retire generated outputs", zap.Error(err))
	}
}

// retiredOutput 是清单上的一个文件,root 是它所在的输出目录。
type retiredOutput struct {
	root, file string
}

// planRetiredOutputs 扫描全部输出目录,只读,返回本次要删的文件。
func planRetiredOutputs(protoRoot string, rules []retireRule) ([]retiredOutput, error) {
	var plan []retiredOutput
	for _, rule := range rules {
		root := filepath.Clean(rule.root)
		if _, err := os.Stat(root); os.IsNotExist(err) {
			continue
		} else if err != nil {
			return nil, err
		}
		if err := checkManagedRoot(root); err != nil {
			return nil, err
		}
		err := filepath.WalkDir(root, func(file string, entry fs.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			// 目录和链接都不碰;WalkDir 不跟链接,清退走不出 root。
			if !entry.Type().IsRegular() {
				return nil
			}
			rel, err := filepath.Rel(root, file)
			if err != nil {
				return err
			}
			state, err := rule.kind.classify(protoRoot, root, filepath.ToSlash(rel))
			if err != nil {
				return err
			}
			switch state {
			case outputRetired:
				plan = append(plan, retiredOutput{root: root, file: file})
			case outputUnproven:
				logger.Global.Warn("Leaving a file that looks generated but cannot be traced to a retired proto",
					zap.String("file", file))
			}
			return nil
		})
		if err != nil {
			return nil, fmt.Errorf("scan %s: %w", root, err)
		}
	}
	return plan, nil
}

// retireOrphanedOutputs 打印清单后删除。中途失败时已删的不回滚:重新生成会接着删剩下的,结果相同。
func retireOrphanedOutputs(protoRoot string, rules []retireRule) error {
	hasSources, err := hasProtoSources(protoRoot)
	if err != nil {
		return err
	}
	if !hasSources {
		return fmt.Errorf("proto root %s has no .proto files; refusing to treat every generated output as retired", protoRoot)
	}
	plan, err := planRetiredOutputs(protoRoot, rules)
	if err != nil {
		return err
	}
	if len(plan) == 0 {
		return nil
	}
	// 整张清单打成一条日志,打完再动手:删到一半失败时,日志里也有本来要删的全部文件。
	// 不逐条打:logger.Init 用的生产配置按消息采样,同一消息一秒内超过 100 条就会丢。
	files := make([]string, 0, len(plan))
	for _, item := range plan {
		files = append(files, item.file)
	}
	logger.Global.Warn(retireLogMessage, zap.Int("count", len(files)), zap.Strings("files", files))
	var errs []error
	for _, item := range plan {
		if err := os.Remove(item.file); err != nil {
			errs = append(errs, fmt.Errorf("remove %s: %w", item.file, err))
			continue
		}
		pruneEmptyDirs(item.root, filepath.Dir(item.file))
	}
	return errors.Join(errs...)
}

// pruneEmptyDirs 从 dir 往上删掉清退后变空的目录,到 root 为止(不含 root)。
func pruneEmptyDirs(root, dir string) {
	for ; dir != root && len(dir) > len(root); dir = filepath.Dir(dir) {
		entries, err := os.ReadDir(dir)
		if err != nil || len(entries) > 0 {
			return
		}
		if err := os.Remove(dir); err != nil {
			logger.Global.Warn("Failed to remove empty generated directory", zap.String("dir", dir), zap.Error(err))
			return
		}
	}
}
