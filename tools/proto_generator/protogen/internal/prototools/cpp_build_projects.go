// SyncCppBuildProjects 让新生成的协议和调用适配器同时进入 Windows 与 Linux 构建。
// 补齐当前协议产物，并清理已退役的官方 gRPC C++ 服务桩；其他手工条目保持原样。
func SyncCppBuildProjects(wg *sync.WaitGroup) {
	wg.Add(1)
	defer wg.Done()
	if !_config.Global.Generators.EnableCpp {
		return
	}
	if err := syncCppBuildProjects(_config.Global.Paths.ProtoDir, _config.Global.Paths.OutputRoot); err != nil {
		logger.Global.Fatal("同步 C++ 生成工程失败", zap.Error(err))
	}
}

func syncCppBuildProjects(protoRoot, outputRoot string) error {
	type update struct{ path, text string }
	var updates []update
	var obsolete []string
	for _, project := range []string{"proto", "grpc_client"} {
		root := filepath.Join(outputRoot, "cpp", "generated", project)
		absoluteRoot, err := filepath.Abs(root)
		if err != nil {
			return err
		}
		realRoot, err := filepath.EvalSymlinks(absoluteRoot)
		if err != nil {
			return err
		}
		if !strings.EqualFold(filepath.Clean(absoluteRoot), filepath.Clean(realRoot)) {
			return fmt.Errorf("受管生成目录不能通过链接重定向: %s", root)
		}
		var sources, headers []string
		err = filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.Type()&os.ModeSymlink != 0 {
				return fmt.Errorf("生成目录中不能包含链接: %s", path)
			}
			if entry.IsDir() {
				return nil
			}
			rel, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}
			rel = filepath.ToSlash(rel)
			if project == "proto" {
				if isOfficialGrpcOutput(rel) {
					body, err := os.ReadFile(path)
					if err != nil {
						return err
					}
					if !strings.HasPrefix(string(body), "// Generated by the gRPC C++ plugin.") {
						return fmt.Errorf("拒绝删除非官方生成的同后缀文件: %s", path)
					}
					obsolete = append(obsolete, path)
					return nil
				}
				if !strings.HasSuffix(rel, ".pb.cc") && !strings.HasSuffix(rel, ".pb.h") {
					return nil
				}
				stem := strings.TrimSuffix(strings.TrimSuffix(rel, ".cc"), ".h")
				stem = strings.TrimSuffix(stem, ".pb")
				if _, err := os.Stat(filepath.Join(protoRoot, filepath.FromSlash(stem+".proto"))); os.IsNotExist(err) {
					return nil
				} else if err != nil {
					return err
				}
			} else if !strings.HasSuffix(rel, "_grpc_client.cpp") && !strings.HasSuffix(rel, "_grpc_client.h") {
				return nil
			}
			if strings.HasSuffix(rel, ".h") {
				headers = append(headers, rel)
			} else {
				sources = append(sources, rel)
			}
			return nil
		})
		if err != nil {
			return err
		}
		sort.Strings(sources)
		sort.Strings(headers)
		for _, name := range []string{"CMakeLists.txt", project + ".vcxproj", project + ".vcxproj.filters"} {
			path := filepath.Join(root, name)
			original, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			text := string(original)
			if project == "proto" {
				text, err = removeOfficialGrpcEntries(name, text)
				if err != nil {
					return fmt.Errorf("%s: %w", path, err)
				}
			}
			text, err = appendCppProjectEntries(name, text, sources, headers)
			if err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
			if strings.HasSuffix(name, ".vcxproj") {
				text, err = migrateGeneratedDependencyConfiguration(text)
				if err != nil {
					return fmt.Errorf("%s: %w", path, err)
				}
			}
			if text != string(original) {
				updates = append(updates, update{path, text})
			}
		}
	}
	// 配置表和元数据工程同样由生成流程维护依赖路径，不手改生成目录中的工程文件。
	for _, project := range []string{"rpc", "table", "proto_helpers"} {
		path := filepath.Join(outputRoot, "cpp", "generated", project, project+".vcxproj")
		original, err := os.ReadFile(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		text, err := migrateGeneratedDependencyConfiguration(string(original))
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if text != string(original) {
			updates = append(updates, update{path, text})
		}
	}
	// 所有清单先校验成功，再写入；不因某个清单形状错误只完成半套登记。
	for _, item := range updates {
		if err := utils.WriteFileIfChanged(item.path, []byte(item.text)); err != nil {
			return err
		}
	}
	// 仅删除当前受管 proto 根目录中已核实生成标记的官方桩，普通消息和 muduo 适配器不受影响。
	for _, path := range obsolete {
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("删除退役官方 gRPC 产物 %s: %w", path, err)
		}
	}
	return nil
}

// 独立依赖布局在生成器处统一迁移，避免下一次生成又带回已移除的 SDK 路径。
func migrateGeneratedDependencyConfiguration(text string) (string, error) {
	groups := regexp.MustCompile(`(?s)<ItemDefinitionGroup\b[^>]*>.*?</ItemDefinitionGroup>`)
	var failure error
	result := groups.ReplaceAllStringFunc(text, func(group string) string {
		prefix := ""
		switch {
		case strings.Contains(group, "'Debug|x64'"):
			prefix = "install_vs2026_dbg"
		case strings.Contains(group, "'Release|x64'"):
			prefix = "install_vs2026_rel"
		case strings.Contains(group, "'Debug|Win32'"):
			prefix = "install_vs2026_x86_dbg"
		case strings.Contains(group, "'Release|Win32'"):
			prefix = "install_vs2026_x86_rel"
		default:
			failure = fmt.Errorf("生成工程的依赖配置必须明确 Debug/Release 与 x64/Win32")
			return group
		}
		for _, tag := range []string{"AdditionalIncludeDirectories", "AdditionalLibraryDirectories", "AdditionalDependencies"} {
			list := regexp.MustCompile(`<` + tag + `>([^<]*)</` + tag + `>`)
			group = list.ReplaceAllStringFunc(group, func(element string) string {
				match := list.FindStringSubmatch(element)
				var entries []string
				for _, entry := range strings.Split(match[1], ";") {
					for _, value := range migrateGeneratedDependencyEntry(tag, entry, prefix) {
						entries = append(entries, value)
					}
				}
				if tag == "AdditionalLibraryDirectories" {
					// 独立 SDK 必须先于公共 lib 搜索，避免同名旧归档覆盖已重建的依赖。
					sdkPath := regexp.MustCompile(`(?i)(?:^|/)third_party/(?:protobuf|boringssl|googletest)/` + regexp.QuoteMeta(prefix) + `/lib/?$`)
					var sdk, other []string
					for _, entry := range entries {
						if sdkPath.MatchString(strings.ReplaceAll(entry, "\\", "/")) {
							sdk = append(sdk, entry)
						} else {
							other = append(other, entry)
						}
					}
					entries = append(sdk, other...)
				}
				return "<" + tag + ">" + strings.Join(entries, ";") + "</" + tag + ">"
			})
		}
		return group
	})
	return result, failure
}

func migrateGeneratedDependencyEntry(tag, entry, prefix string) []string {
	if tag == "AdditionalDependencies" {
		name := strings.ToLower(entry)
		if (strings.HasPrefix(name, "grpc") && name != "grpc_client.lib") || strings.HasPrefix(name, "upb_") {
			return nil
		}
		switch name {
		case "address_sorting.lib", "cares.lib", "gpr.lib", "re2.lib", "libupb.lib", "libupbd.lib", "utf8_range_lib.lib":
			return nil
		case "utf8_range.lib":
			return []string{"libutf8_range.lib"}
		case "utf8_validity.lib":
			return []string{"libutf8_validity.lib"}
		case "gtestd.lib":
			return []string{"gtest.lib"}
		}
		debug := strings.HasSuffix(prefix, "_dbg")
		for _, base := range []string{"libprotobuf", "libprotobuf-lite", "libprotoc"} {
			if name == base+".lib" || name == base+"d.lib" {
				if debug {
					return []string{base + "d.lib"}
				}
				return []string{base + ".lib"}
			}
		}
		return []string{entry}
	}
	value := strings.ReplaceAll(entry, "\\", "/")
	if strings.Contains(value, "third_party/grpc/include") {
		return nil
	}
	if tag == "AdditionalLibraryDirectories" {
		if before, _, ok := strings.Cut(value, "third_party/grpc/install_"); ok {
			return []string{before + "third_party/protobuf/" + prefix + "/lib/", before + "third_party/boringssl/" + prefix + "/lib/", before + "third_party/googletest/" + prefix + "/lib/"}
		}
	}
	for _, pair := range [][2]string{
		{"third_party/grpc/third_party/protobuf", "third_party/protobuf"},
		{"third_party/grpc/third_party/abseil-cpp", "third_party/abseil-cpp"},
		{"third_party/protobuf/third_party/abseil-cpp", "third_party/abseil-cpp"},
		{"third_party/grpc/third_party/googletest", "third_party/googletest"},
		{"third_party/grpc/third_party/utf8_range", "third_party/protobuf/third_party/utf8_range"},
		{"third_party/grpc/third_party/boringssl-with-bazel/include", "third_party/boringssl/" + prefix + "/include"},
	} {
		value = strings.ReplaceAll(value, pair[0], pair[1])
	}
	if value == strings.ReplaceAll(entry, "\\", "/") {
		return []string{entry}
	}
	return []string{value}
}

func isOfficialGrpcOutput(path string) bool {
	return strings.HasSuffix(path, ".grpc.pb.cc") || strings.HasSuffix(path, ".grpc.pb.h")
}

// removeOfficialGrpcEntries 只接受独立源码条目。遇到条件、额外属性或编译元数据时拒绝整次同步。
func removeOfficialGrpcEntries(name, text string) (string, error) {
	if name == "CMakeLists.txt" {
		anchor := regexp.MustCompile(`(?ms)^set\(SOURCE_FILES[ \t]*\r?\n(.*?)^\)`)
		matches := anchor.FindAllStringSubmatchIndex(text, -1)
		if len(matches) != 1 {
			return "", fmt.Errorf("SOURCE_FILES 必须恰好一段")
		}
		match := matches[0]
		var kept []string
		for _, line := range strings.SplitAfter(text[match[2]:match[3]], "\n") {
			value := strings.TrimSpace(line)
			if strings.Contains(value, ".grpc.pb.") {
				if !isOfficialGrpcOutput(value) || !filepath.IsLocal(filepath.FromSlash(value)) || strings.ContainsAny(value, " \t\";$") {
					return "", fmt.Errorf("官方 gRPC 源条目包含非标准 CMake 配置: %s", value)
				}
				continue
			}
			kept = append(kept, line)
		}
		return text[:match[2]] + strings.Join(kept, "") + text[match[3]:], nil
	}
	if strings.Count(text, "</Project>") != 1 {
		return "", fmt.Errorf("Project 结束标签必须恰好一个")
	}
	conditional := regexp.MustCompile(`(?s)<ItemGroup\b[^>]*\bCondition=[^>]*>.*?</ItemGroup>`)
	for _, group := range conditional.FindAllString(text, -1) {
		if strings.Contains(group, ".grpc.pb.") {
			return "", fmt.Errorf("官方 gRPC 条目处于条件组中，拒绝自动移除")
		}
	}
	simple := regexp.MustCompile(`(?m)^[ \t]*<(ClCompile|ClInclude) Include="([^"\r\n]+\.grpc\.pb\.(?:cc|h))"(?:[ \t]*/>|>[ \t]*\r?\n[ \t]*<Filter>[^<]*</Filter>[ \t]*\r?\n[ \t]*</(?:ClCompile|ClInclude)>)[ \t]*\r?\n`)
	var invalid string
	cleaned := simple.ReplaceAllStringFunc(text, func(item string) string {
		match := simple.FindStringSubmatch(item)
		if !filepath.IsLocal(filepath.FromSlash(strings.ReplaceAll(match[2], "\\", "/"))) {
			invalid = match[2]
			return item
		}
		return ""
	})
	if invalid != "" || strings.Contains(cleaned, ".grpc.pb.") {
		return "", fmt.Errorf("官方 gRPC 条目含路径越界、条件或自定义元数据，拒绝自动移除")
	}
	return cleaned, nil
}

func appendCppProjectEntries(name, text string, sources, headers []string) (string, error) {
	newline := "\n"
	if strings.Contains(text, "\r\n") {
		newline = "\r\n"
	}
	if name == "CMakeLists.txt" {
		anchor := regexp.MustCompile(`(?ms)^set\(SOURCE_FILES[ \t]*\r?\n(.*?)^\)`)
		matches := anchor.FindAllStringSubmatchIndex(text, -1)
		if len(matches) != 1 {
			return "", fmt.Errorf("SOURCE_FILES 必须恰好一段")
		}
		match := matches[0]
		existing := map[string]bool{}
		for _, line := range strings.Split(text[match[2]:match[3]], "\n") {
			existing[strings.TrimSpace(line)] = true
		}
		var lines []string
		for _, source := range sources {
			if !existing[source] {
				lines = append(lines, "    "+source)
			}
		}
		if len(lines) == 0 {
			return text, nil
		}
		return text[:match[3]] + strings.Join(lines, newline) + newline + text[match[3]:], nil
	}
	if strings.Count(text, "</Project>") != 1 {
		return "", fmt.Errorf("Project 结束标签必须恰好一个")
	}
	// 历史 post-hook 会在普通 ItemGroup 追加 mail/rank，旧生成区因此可能留下同路径的第二份。
	// MSBuild /m:1 也挡不住项目内 /MP 同时写同一个 obj。只清理本生成器拥有的简单条目，
	// 普通区及带手工编译选项的条目保持原样；优先保留普通区，避免丢掉调用方配置。
	managed := regexp.MustCompile(`(?ms)[ \t]*<ItemGroup Label="ProtoGeneratorSources">.*?</ItemGroup>[ \t]*\r?\n?`)
	itemStart := regexp.MustCompile(`<(ClCompile|ClInclude)\s+Include="([^"]+)"`)
	seen := map[string]bool{}
	itemKey := func(tag, path string) string {
		return tag + ":" + strings.ToLower(strings.ReplaceAll(path, "\\", "/"))
	}
	for _, match := range itemStart.FindAllStringSubmatch(managed.ReplaceAllString(text, ""), -1) {
		seen[itemKey(match[1], match[2])] = true
	}
	simpleItem := regexp.MustCompile(`(?m)^[ \t]*<(ClCompile|ClInclude)\s+Include="([^"]+)"(?:[ \t]*/>|>[ \t]*\r?\n[ \t]*<Filter>[^<]*</Filter>[ \t]*\r?\n[ \t]*</(?:ClCompile|ClInclude)>)[ \t]*\r?\n`)
	text = managed.ReplaceAllStringFunc(text, func(block string) string {
		return simpleItem.ReplaceAllStringFunc(block, func(item string) string {
			match := simpleItem.FindStringSubmatch(item)
			key := itemKey(match[1], match[2])
			if seen[key] {
				return ""
			}
			seen[key] = true
			return item
		})
	})
	var additions []string
	for _, group := range []struct {
		tag, filter string
		files       []string
	}{{"ClCompile", "源文件", sources}, {"ClInclude", "头文件", headers}} {
		existing := map[string]bool{}
		pattern := regexp.MustCompile(`<` + group.tag + `\s+Include="([^"]+)"`)
		for _, match := range pattern.FindAllStringSubmatch(text, -1) {
			existing[strings.ReplaceAll(match[1], "\\", "/")] = true
		}
		for _, file := range group.files {
			if existing[file] {
				continue
			}
			file = strings.ReplaceAll(file, "/", "\\")
			if strings.HasSuffix(name, ".filters") {
				additions = append(additions, fmt.Sprintf("    <%s Include=\"%s\">%s      <Filter>%s</Filter>%s    </%s>", group.tag, file, newline, group.filter, newline, group.tag))
			} else {
				additions = append(additions, fmt.Sprintf("    <%s Include=\"%s\" />", group.tag, file))
			}
		}
	}
	if len(additions) == 0 {
		return text, nil
	}
	block := "  <ItemGroup Label=\"ProtoGeneratorSources\">" + newline + strings.Join(additions, newline) + newline + "  </ItemGroup>" + newline
	return strings.Replace(text, "</Project>", block+"</Project>", 1), nil
}
