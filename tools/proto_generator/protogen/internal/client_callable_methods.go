// WriteGoClientCallableMethods 生成 Go 在线服务共用的「客户端可发起方法」集合
// (docs/design/gate-online-identity.md §9.2),输出到 go/shared/generated/clientrpc。
//
// 收录规则与 gate 上行白名单 IsClientMessageId 用同一份分类(ClassifyClientRpcServices + AcceptsClientUpstream):
// 服务标了 OptionIsClientProtocolService,方法形态是 REQUEST 或 ONE_WAY。PUSH 只下行;SERVER_ONLY 由服务端或
// gate 代发(login 的 Disconnect),都不收。只收 gRPC 形态的服务:scene TCP 方法不经 Go 服务,DB 域不对客户端。
//
// 消费方是各在线服务的入口拦截器(shared/roleidentity):集合里的方法必须带会话,带会话的请求只能调集合里的方法。
// 路由服不用它:gate 代发的 Disconnect 要经路由服转给 login。
func WriteGoClientCallableMethods(wg *sync.WaitGroup) {
	wg.Add(1)
	go func() {
		defer wg.Done()
		outputPath := _config.Global.Paths.ClientCallableMethodsFile
		if strings.TrimSpace(outputPath) == "" {
			logger.Global.Warn("client_callable_methods_file not configured, skipping client callable method set generation")
			return
		}
		methods, err := collectClientCallableMethods(GlobalRPCServiceList, IsSceneTCPMethod)
		if err != nil {
			logger.Global.Fatal("Failed to collect client callable methods", zap.Error(err))
		}
		formatted, err := renderClientCallableMethods(methods)
		if err != nil {
			logger.Global.Fatal("Generated client callable method set is not valid Go",
				zap.String("file_path", outputPath),
				zap.Error(err))
		}
		if err := utils.WriteFileIfChanged(outputPath, formatted); err != nil {
			logger.Global.Fatal("Failed to write client callable method set",
				zap.String("file_path", outputPath),
				zap.Error(err))
		}
		logger.Global.Info("Client callable method set generated",
			zap.String("file_path", outputPath),
			zap.Int("methods", len(methods)))
	}()
}

// collectClientCallableMethods 返回去重并按字典序排好的 gRPC 方法全名:"/<package>.<Service>/<Method>",
// proto 无 package 时为 "/<Service>/<Method>",与 protoc 生成的 *_FullMethodName 及 grpc.UnaryServerInfo.FullMethod 一致。
// 调用时机同 ClassifyClientRpcServices:方法号已分配之后。分类违例原样返回,调用方 Fatal。
func collectClientCallableMethods(services RPCServiceInfoList, isSceneTCP SceneTCPPredicate) ([]string, error) {
	classified, err := ClassifyClientRpcServices(services, isSceneTCP)
	if err != nil {
		return nil, err
	}
	seen := make(map[string]struct{})
	var methods []string
	for _, service := range classified {
		info := service.Service
		if info.CcGenericServices() || IsFileBelongToNode(info.Fd, messageoption.NodeType_NODE_DB) {
			continue
		}
		serviceFullName := info.Service()
		if pkg := info.Package(); pkg != "" {
			serviceFullName = pkg + "." + info.Service()
		}
		for _, method := range service.Methods {
			if !method.Kind.AcceptsClientUpstream() {
				continue
			}
			fullMethod := "/" + serviceFullName + "/" + method.Method.Method()
			if _, dup := seen[fullMethod]; dup {
				continue
			}
			seen[fullMethod] = struct{}{}
			methods = append(methods, fullMethod)
		}
	}
	sort.Strings(methods)
	return methods, nil
}

// renderClientCallableMethods 拼出生成物源码并过 gofmt。
func renderClientCallableMethods(methods []string) ([]byte, error) {
	var sb strings.Builder
	sb.WriteString("// Code generated by protogen. DO NOT EDIT.\n")
	sb.WriteString("//\n")
	sb.WriteString("// 客户端可发起的 gRPC 方法全名(docs/design/gate-online-identity.md §9.2)。事实源是 proto/ 下各服务的\n")
	sb.WriteString("// OptionIsClientProtocolService 与方法级 OptionClientRpcKind;改 proto 后重跑 proto-gen-run,不要手改。\n\n")
	sb.WriteString("// Package clientrpc 回答「客户端能不能发起这个 gRPC 方法」,与 gate 上行白名单同一份分类。\n")
	sb.WriteString("package clientrpc\n\n")
	sb.WriteString("var callable = map[string]struct{}{\n")
	for _, method := range methods {
		sb.WriteString(fmt.Sprintf("\t%q: {},\n", method))
	}
	sb.WriteString("}\n\n")
	sb.WriteString("// Callable 报告客户端能否发起 fullMethod(gRPC 方法全名,即 grpc.UnaryServerInfo.FullMethod)。\n")
	sb.WriteString("// PUSH、SERVER_ONLY 与非客户端协议服务的方法都返回 false。\n")
	sb.WriteString("func Callable(fullMethod string) bool {\n")
	sb.WriteString("\t_, ok := callable[fullMethod]\n")
	sb.WriteString("\treturn ok\n")
	sb.WriteString("}\n")
	return format.Source([]byte(sb.String()))
}
