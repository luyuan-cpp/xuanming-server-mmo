// 收录规则与 gate 上行白名单同一份分类:只收 REQUEST / ONE_WAY。PUSH 与 SERVER_ONLY(gate 代发的 Disconnect 一类)不收,
// 没标 OptionIsClientProtocolService 的内部服务(RoleFenceParticipant 一类)也不收。
func TestClientCallableMethodsFollowClientRpcKind(t *testing.T) {
	guild, _ := clientRpcRegressionService()
	guild.Fd.Package = proto.String("guildpb")
	clientRpcRegressionSetKind(clientRpcRegressionAddMethod(guild, "NotifyGuildChanged", ".guildpb.GuildChangedS2C", ".Empty"), uint64(ClientRpcPush))
	clientRpcRegressionSetKind(clientRpcRegressionAddMethod(guild, "UpdateGuildScore", ".fixture.Request", ".fixture.Response"), uint64(ClientRpcServerOnly))
	clientRpcRegressionAddMethod(guild, "GetGuild", ".fixture.Request", ".fixture.Response")
	internalService := routeTestService("proto/role_fence/role_fence.proto", "RoleFenceParticipant", false)

	methods, err := collectClientCallableMethods(RPCServiceInfoList{guild, internalService}, func(*MethodInfo) bool { return false })
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"/guildpb.GuildService/Call", "/guildpb.GuildService/GetGuild"}
	if !slices.Equal(methods, want) {
		t.Fatalf("客户端可发起方法 = %v, want %v", methods, want)
	}
}

// proto 没有 package 时全名是 "/<Service>/<Method>",与 protoc 生成的 FullMethodName 一致。
func TestClientCallableMethodsWithoutPackage(t *testing.T) {
	service, _ := clientRpcRegressionService()
	methods, err := collectClientCallableMethods(RPCServiceInfoList{service}, func(*MethodInfo) bool { return false })
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"/GuildService/Call"}; !slices.Equal(methods, want) {
		t.Fatalf("客户端可发起方法 = %v, want %v", methods, want)
	}
}

// scene TCP 服务(cc_generic_services)由 gate 直接转给 scene,不经任何 Go 服务,不进集合。
func TestClientCallableMethodsSkipSceneTCPServices(t *testing.T) {
	scene, _ := clientRpcRegressionService()
	scene.Fd.Options = &descriptorpb.FileOptions{CcGenericServices: proto.Bool(true)}
	methods, err := collectClientCallableMethods(RPCServiceInfoList{scene}, func(*MethodInfo) bool { return true })
	if err != nil {
		t.Fatal(err)
	}
	if len(methods) != 0 {
		t.Fatalf("scene TCP 服务不该进集合: %v", methods)
	}
}

// 分类违例(这里是 Notify 开头却没标 PUSH)要让生成失败,不能产出一份漏判的集合。
func TestClientCallableMethodsPropagateClassificationError(t *testing.T) {
	service, _ := clientRpcRegressionService()
	clientRpcRegressionAddMethod(service, "NotifyUnmarked", ".fixture.Request", ".fixture.Response")
	methods, err := collectClientCallableMethods(RPCServiceInfoList{service}, func(*MethodInfo) bool { return false })
	if err == nil || methods != nil {
		t.Fatalf("分类违例必须让生成失败: methods=%v err=%v", methods, err)
	}
}

func TestRenderClientCallableMethodsIsGofmtSource(t *testing.T) {
	source, err := renderClientCallableMethods([]string{"/chatpb.ClientPlayerChat/SendChat"})
	if err != nil {
		t.Fatal(err)
	}
	text := string(source)
	for _, want := range []string{"// Code generated by protogen. DO NOT EDIT.", "package clientrpc", `"/chatpb.ClientPlayerChat/SendChat": {},`, "func Callable(fullMethod string) bool"} {
		if !strings.Contains(text, want) {
			t.Fatalf("生成物缺少 %q:\n%s", want, text)
		}
	}
}
