#requires -Version 7
<#
.SYNOPSIS
    重新生成 t2s.txt(繁体 → 简体的逐字对照表)。只在要更新字表时手工跑,不进构建。
.DESCRIPTION
    来源是 Windows 自带的简繁转换(LCMapString 的 LCMAP_SIMPLIFIED_CHINESE,经 VB 的 StrConv 调用),
    范围是 CJK 扩展 A 与基本区(U+3400 – U+9FFF)。Windows 的表偏保守,下面 $supplement 里的几个常用字它不转,手工补上。
    字表只用于匹配前的归一化:词库和待检文字走同一张表,所以「多转了一个字」不会造成漏判或误判,只要两边一致。
    只能在 Windows 上跑(StrConv 的简繁转换在别的平台不可用);产物 t2s.txt 提交进仓库,运行期不依赖本脚本。
.EXAMPLE
    pwsh -File go/content_guard/internal/textnorm/gen_t2s.ps1
#>
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName Microsoft.VisualBasic

# Windows 不转、但词库里常见的字。左繁右简。
$supplement = [ordered]@{ '後' = '后'; '於' = '于'; '乾' = '干'; '藉' = '借'; '徵' = '征'; '夥' = '伙'; '嚐' = '尝' }

$pairs = [System.Collections.Generic.SortedDictionary[int, string]]::new()
foreach ($range in @(@(0x3400, 0x4DBF), @(0x4E00, 0x9FFF))) {
    for ($cp = $range[0]; $cp -le $range[1]; $cp++) {
        $source = [string][char]$cp
        $target = [Microsoft.VisualBasic.Strings]::StrConv($source, [Microsoft.VisualBasic.VbStrConv]::SimplifiedChinese, 2052)
        # 转不了的字(不在 Windows 那张表覆盖范围内)会得到 '?',只收结果仍是汉字的。
        if ($target.Length -eq 1 -and $target -ne $source -and [int][char]$target -ge 0x3400) { $pairs[$cp] = $source + $target }
    }
}
foreach ($key in $supplement.Keys) { $pairs[[int][char]$key] = $key + $supplement[$key] }

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Traditional -> Simplified, one pair per line (traditional first). Generated by gen_t2s.ps1; do not edit by hand.')
foreach ($value in $pairs.Values) { $lines.Add($value) }
$path = Join-Path $PSScriptRoot 't2s.txt'
[System.IO.File]::WriteAllText($path, (($lines -join "`n") + "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "wrote $($pairs.Count) pairs to $path"
